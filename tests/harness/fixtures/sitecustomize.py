"""Точка входа приспособлений дочернего сервера сценария (`given.fixtures`).

Python импортирует один `sitecustomize` — первый на пути, поэтому он один на все приспособления: `VPM_FIXTURES=имя,имя`
называет модули этого каталога. Неизвестное имя или упавшее приспособление — отказ старта с именем, а не тихий пропуск:
сценарий без своей причины прошёл бы на обычной среде. Приспособления ставятся ровно в процесс, которому их назвали:
дочерние интерпретаторы (свои у приспособления, раннер и pip у сервера) их не наследуют.
"""
import importlib
import os
import sys
from pathlib import Path

# Корень проекта этой точки входа — первым: пока идёт site, каталога скрипта на пути ещё нет, и `core` взялся бы
# из установки проекта в режиме редактирования (живое дерево), а не из копии, где поднят сервер.
sys.path.insert(0, str(Path(__file__).resolve().parents[3]))

# Снято до импорта: ребёнок, запущенный приспособлением при импорте, иначе ставит его снова — цепочка без конца.
for _name in filter(None, (part.strip() for part in os.environ.pop("VPM_FIXTURES", "").split(","))):
    try:
        importlib.import_module(_name)
    except Exception as e:
        sys.stderr.write(f"ПРИСПОСОБЛЕНИЕ НЕ ПОСТАВЛЕНО: {_name} — {type(e).__name__}: {e}\n")
        raise SystemExit(1) from None   # site превращает выход в фатальную ошибку инициализации: код 1, старт не идёт
