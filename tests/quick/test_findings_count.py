"""
tests/quick/test_findings_count.py — судья читаемости реестра проверяется без реестра.

Зовёт: `findings_count` (сам судья — его разбор, образец живой формы и состояния строки) и
`invariants` (соседняя ось статусов, слепнущая вместе со счётом). Вход НЕ пишется здесь: он
снимается с живого реестра объявленными `ПРАВКИ` из `tests/scenarios/steps` — тем же списком,
каким пользуются сценарии трёх родов.

Проверяет: что считается строкой реестра и что закрытием, пол ловит ужавшийся разбор и молчит на
выросшем, отсутствие улики (нет реестра, нет пола, ноль строк) объявляется отдельно от «чисто»,
и разбор у реестра ОДИН — второй читатель дал бы второй вердикт.
"""
import io
import sys
import tempfile
from contextlib import redirect_stderr, redirect_stdout
from pathlib import Path
from types import ModuleType

ROOT = Path(__file__).resolve().parents[2]
GUARDS = ROOT / "scripts" / "guards"
sys.path.insert(0, str(GUARDS))

def _load(path: Path, name: str):
    """Компиляция ИЗ ИСХОДНИКА: кэш байткода признаёт свежим .pyc при том же размере и секунде."""
    module = ModuleType(name)
    module.__file__ = str(path)
    exec(compile(path.read_text(encoding="utf-8"), str(path), "exec"), module.__dict__)
    return module


sys.dont_write_bytecode = True
fc = _load(GUARDS / "findings_count.py", "findings_count")
sys.modules["findings_count"] = fc            # соседу достаётся ТОТ ЖЕ свежий разбор, а не свой кэш
inv = _load(GUARDS / "invariants.py", "invariants")

_checks = 0
_fails = []


def ok(cond, msg):
    global _checks
    _checks += 1
    if not cond:
        _fails.append(msg)
    print(f"  {'✓' if cond else '✗'} {msg}")


_роспись: list[dict] = []


def _шаг(имя):
    return next((р for р in _роспись if р["имя"] == имя), None)


def run(registry: str | None, floor: str | None, *argv) -> tuple[int, str, str]:
    """Прогон судьи на подставленных файлах: настоящий реестр не трогается.

    Роспись перехватывается, а не пишется в журнал: судим РЯДЫ — на каком шаге прогон замолчал и
    какое условие его остановило. Запись в журнал доказала бы лишь вызов.
    """
    tmp = Path(tempfile.mkdtemp(prefix="vpm_findings_"))
    fc.REGISTRY = tmp / "02_findings.md"
    fc.FLOOR = tmp / "floor.txt"
    if registry is not None:
        fc.REGISTRY.write_text(registry, encoding="utf-8")
    if floor is not None:
        fc.FLOOR.write_text(floor, encoding="utf-8")
    out, err = io.StringIO(), io.StringIO()
    _роспись.clear()
    было_роспись = fc._stamp.роспись
    fc._stamp.роспись = lambda ряды, **к: (_роспись.extend(ряды), ("0000", "—"))[1]
    argv_backup = sys.argv
    sys.argv = ["findings_count.py", *argv]
    try:
        with redirect_stdout(out), redirect_stderr(err):
            code = fc.main()
    except Exception as exc:                      # падение судьи — это провал проверки, а не прогона
        code, err = -1, io.StringIO(f"судья упал: {type(exc).__name__}: {exc}\n")
    finally:
        sys.argv = argv_backup
        fc._stamp.роспись = было_роспись
    return code, out.getvalue(), err.getvalue()


# Улике не место в наборе — правило владельца 2026-09-14: «мы только в радиус пишем, и не улику, а
# набор команд, который через цепочку воспроизводит дыру». Поэтому вход не пишется здесь ни одной
# строкой: он СНИМАЕТСЯ с живого источника и правится ОБЪЯВЛЕННОЙ правкой — тем же списком, каким
# пользуются сценарии трёх родов (`tests/scenarios/steps.ПРАВКИ`), чтобы машина была одна.
# Границы самого разбора (§1) по-прежнему сочиняются: там предмет пробы — регулярка, а не форма.
sys.path.insert(0, str(ROOT))
from tests.scenarios.steps import ПРАВКИ  # noqa: E402 — один список правок на набор и сценарии

ИСТОЧНИК = ROOT / "docs" / "roadmap" / "02_findings.md"
ОБРАЗЕЦ = fc.образец()


def снимок(правка: str = "как-есть") -> str:
    """Живой реестр под объявленной правкой: ни строки источника в наборе, только имя правки."""
    return ПРАВКИ[правка](ИСТОЧНИК.read_text(encoding="utf-8"))


def в_состоянии(род: str, имя: str) -> str:
    """Живая строка реестра в объявленном состоянии: проба называет СОСТОЯНИЕ, а не содержимое."""
    return fc.состояние(ОБРАЗЕЦ[род], имя)


def закрыта(текст: str) -> bool:
    """Разбор нашёл строку И она закрыта. Пустой разбор истиной не считается: `all({})` — True, и
    «ничего не разобралось» читалось бы как «всё верно»."""
    свод = fc.scan(текст)
    return bool(свод) and all(свод.values())


def открыта(текст: str) -> bool:
    """Разбор нашёл строку И она открыта — с той же защитой от пустого разбора."""
    свод = fc.scan(текст)
    return bool(свод) and not any(свод.values())


def чужая_таблица() -> str:
    """Строка ЖИВОГО каталога мутаций: чужая таблица с идентификатором в ячейке — не находка."""
    for строка in (ROOT / "tests" / "CATALOG.md").read_text(encoding="utf-8").splitlines():
        if строка.startswith("| M") and строка.count("|") > 3:
            return строка
    raise AssertionError("в tests/CATALOG.md не нашлось ни одной строки мутации — судить нечем")


def замер(текст: str) -> str:
    """Пол по ЭТОМУ снимку: число считается разбором, а не пишется цифрой, которая протухнет."""
    return str(len(fc.scan(текст)))


def main() -> int:
    print("§1 что считается строкой реестра")
    ok(открыта(в_состоянии("открытая", "как-есть")),
       "живая открытая строка разобрана как открытая")
    ok(закрыта(в_состоянии("открытая", "зачёркнутая-без-знака")),
       "зачёркнутый идентификатор — закрытие даже без галочки")
    ok(закрыта(в_состоянии("закрытая", "жирный")),
       "жирный идентификатор виден, знак закрытия прочитан")
    # Перебираем ВСЕ объявленные знаки, а не один: добавят знак в реестр — проба покроет его сама,
    # а зашитый в пробу символ молчал бы о новом ровно до первой беды.
    ok(all(закрыта(fc.со_знаком(ОБРАЗЕЦ["открытая"], знак)) for знак in fc.CLOSED),
       "каждый объявленный знак закрытия читается закрытием")
    # Знак живёт В ОДНОМ месте: формула, где он написан ещё раз, переживёт смену палитры реестра и
    # будет судить старое. Считаем по исходнику судьи — вторую копию иначе не увидеть.
    исходник = (GUARDS / "findings_count.py").read_text(encoding="utf-8")
    вне_объявления = [n for n, строка in enumerate(исходник.splitlines(), 1)
                      if any(знак in строка for знак in fc.CLOSED) and "CLOSED = " not in строка]
    ok(not вне_объявления,
       "знаки закрытия названы РОВНО в объявлении судьи: вторая копия рухнет от смены палитры")
    if вне_объявления:
        print(f"      факт: знак встречается вне объявления в строках {вне_объявления}")
    ok(закрыта(в_состоянии("открытая", "знак-перехода")),
       "переход в закрытое читается по итоговому знаку, а не по начальному")

    print("§2 что строкой реестра НЕ считается")
    ok(fc.scan(чужая_таблица()) == {},
       "строка ЖИВОГО каталога мутаций находкой не считается: чужая таблица — чужой реестр")
    ok(fc.scan(в_состоянии("открытая", "проза")) == {},
       "упоминание вне таблицы не считается")
    ok(fc.scan(в_состоянии("открытая", "чужая-серия")) == {},
       "идентификатор чужой серии реестром находок не считается")
    ok(fc.scan(ОБРАЗЕЦ["шапка"] + "\n" + ОБРАЗЕЦ["разделитель"]) == {},
       "шапка и разделитель ИЗ ИСТОЧНИКА строками не считаются")

    print("§3 повтор идентификатора: первая строка каноническая")
    # Повтор строится из ОДНОЙ живой строки в двух состояниях: так проверяется правило «первая
    # каноническая», а не наша способность написать две похожие строки руками.
    канон_открыт = (в_состоянии("открытая", "как-есть") + "\n"
                    + в_состоянии("открытая", "знак-закрытия"))
    ok(открыта(канон_открыт),
       "нижняя таблица не закрывает находку за канон")
    канон_закрыт = (в_состоянии("открытая", "знак-закрытия") + "\n"
                    + в_состоянии("открытая", "как-есть"))
    ok(закрыта(канон_закрыт),
       "и наоборот: канон закрыт — нижняя строка его не открывает")

    print("§4 пол ловит ужавшийся разбор")
    полный = снимок()
    code, out, err = run(снимок("половина-строк"), замер(полный), "--check")
    ok(code == 1, f"разобрано меньше пола — отказ (код {code})")
    ok("сломался разбор" in err, "названа ПРИЧИНА: не «закрыли находки», а сломался разбор")
    ok("status_off_registry" in err, "названо, кто ещё слепнет вместе со счётом")
    code, out, err = run(полный, замер(полный), "--check")
    ok(code == 0, f"ровно пол — не отказ (код {code})")
    ok("читается машиной" in out, "молчание сказано вслух, а не пустым выводом")
    code, out, err = run(полный, str(int(замер(полный)) - 1), "--check")
    ok(code == 0, "реестр вырос — отказа нет: находки не удаляются, только добавляются")

    print("§5 «улики нет» — отдельный исход, а не чистый результат")
    code, out, err = run(None, замер(полный), "--check")
    ok(code == 2, f"реестра нет — код 2, а не 0 и не 1 (получено {code})")
    code, out, err = run(снимок("сдвиг-разметки"), замер(полный), "--check")
    ok(code == 2, f"ни одной строки не разобрано — код 2 (получено {code})")
    ok("замер не состоялся" in err, "сказано, что замера не было, а не что реестр пуст")
    code, out, err = run(полный, None, "--check")
    ok(code == 2, f"файла пола нет — храповик молча не выключается (код {code})")
    ok("пол" in err.lower(), "названо, чего не хватает")
    code, out, err = run(полный, "не число", "--check")
    ok(code == 2, f"пол испорчен — код 2, а не питонов трейс (код {code})")

    print("§5б образец: форму судят ПО ИСТОЧНИКУ, а не по копии в наборе")
    ok(открыта(ОБРАЗЕЦ["открытая"]) and закрыта(ОБРАЗЕЦ["закрытая"]),
       "живые строки реестра разбираются разбором судьи: набор и сторож смотрят на ОДНУ форму")
    ok(закрыта(ОБРАЗЕЦ["закрытая"]) and открыта(ОБРАЗЕЦ["открытая"]),
       "род живой строки читается из неё самой: закрытая закрыта, открытая открыта")
    ok(fc.scan(ОБРАЗЕЦ["шапка"] + "\n" + ОБРАЗЕЦ["разделитель"]) == {},
       "шапка и разделитель ИЗ ИСТОЧНИКА находками не считаются — граница проверена на живом, а "
       "не на сочинённом")
    сдвинутый = Path(tempfile.mkdtemp()) / "02_findings.md"
    сдвинутый.write_text(
        (ROOT / "docs" / "roadmap" / "02_findings.md").read_text(encoding="utf-8")
        .replace("| F", "|  F").replace("| ~~F", "|  ~~F"), encoding="utf-8")
    try:
        fc.образец(сдвинутый)
        ok(False, "форма источника сдвинулась — набор обязан ОСТАНОВИТЬСЯ, а не судить по копии")
    except fc.НетОбразца as отказ:
        ok("форма источника неполна" in str(отказ),
           "форма источника сдвинулась — набор обязан ОСТАНОВИТЬСЯ, а не судить по копии")
    try:
        fc.образец(Path(tempfile.mkdtemp()) / "нет.md")
        ok(False, "источника нет — отказ с названной причиной, а не пустой словарь")
    except fc.НетОбразца as отказ:
        ok("форму брать неоткуда" in str(отказ),
           "источника нет — отказ с названной причиной, а не пустой словарь")

    print("§5а роспись: на каком шаге прогон замолчал и что его остановило")
    run(полный, замер(полный), "--check")
    ok(_шаг("сверить с полом") is not None and _шаг("сверить с полом")["исход"] == "молчал"
       and "не ниже пола" in _шаг("сверить с полом")["следствие"],
       "роспись: зелёный прогон объясняет, ПОЧЕМУ храповик промолчал, — сверка состоялась")
    run(снимок("половина-строк"), замер(полный), "--check")
    ok(_шаг("сверить с полом")["исход"] == "сработал"
       and "ужался" in _шаг("сверить с полом")["следствие"],
       "роспись: ужавшийся реестр — СРАБАТЫВАНИЕ шага, а не строка в stderr")
    run(None, замер(полный), "--check")
    ok(_шаг("поднять реестр") is not None and _шаг("поднять реестр")["исход"] == "молчал"
       and "ноль строк тут не чистота" in _шаг("поднять реестр")["следствие"],
       "роспись пишется и на ОТКАЗЕ: без источника прогон обязан объяснить себя, иначе его не "
       "отличить от зелёного")
    run(полный, None, "--check")
    ok(_шаг("сверить с полом") is not None and _шаг("сверить с полом")["исход"] == "молчал"
       and "храповик выключен" in _шаг("сверить с полом")["следствие"],
       "роспись: выключенный храповик назван шагом — иначе «пола нет» неотличимо от «пол сошёлся»")
    run(полный, "1", "--check", "--root", str(Path(tempfile.mkdtemp())))
    ok(not _роспись,
       "чужое дерево НЕ расписывается: ряд о чужой мерке в нашем журнале читался бы как шаг по "
       "своему — та же причина, по которой туда не уходит подпись вердикта")

    print("§6 --bless поднимает пол и не притворяется проверкой")
    tmp = Path(tempfile.mkdtemp(prefix="vpm_findings_"))
    fc.REGISTRY, fc.FLOOR = tmp / "r.md", tmp / "floor.txt"
    fc.REGISTRY.write_text(снимок(), encoding="utf-8")
    fc.FLOOR.write_text("1\n", encoding="utf-8")
    argv_backup = sys.argv
    sys.argv = ["findings_count.py", "--check", "--bless"]
    with redirect_stdout(io.StringIO()):
        code = fc.main()
    sys.argv = argv_backup
    поднятый = fc.FLOOR.read_text(encoding="utf-8").strip()
    ok(code == 0 and поднятый == замер(снимок()), "пол поднят до замера")
    if поднятый != замер(снимок()):
        print(f"      факт: пол {поднятый}, замер {замер(снимок())}")
    code, out, err = run(полный, "9", "--bless")
    # Ищем ПРИЗНАК суда по полу («при поле»), а не цифру: одинокая «9» встречается в любом живом
    # тексте находки, и проба краснела бы от содержимого реестра, а не от поведения судьи.
    ok(code == 0 and "при поле" not in (out + err) and "ужался" not in (out + err),
       "--bless без --check не молчит и не судит по старому полу")

    print("§7 у реестра ОДИН разбор")
    ok(not hasattr(inv, "REGISTRY_ROW"),
       "в invariants нет второго разбора строк реестра: два читателя дают два вердикта")
    real = (ROOT / "docs" / "roadmap" / "02_findings.md").read_text(encoding="utf-8")
    mine = fc.scan(real)
    theirs = inv._registry_status(ROOT)
    ok(set(mine) == set(theirs), f"оба читателя видят один набор строк  → {len(mine)} и {len(theirs)}")
    clash = sorted(f for f in set(mine) & set(theirs)
                   if ("закрыт" if mine[f] else "открыт") != theirs[f])
    ok(not clash, f"вердикт совпадает по каждой находке; расходятся: {clash}")

    print("§8 пространство состояний обходится ОБЪЯВЛЕНИЕМ, а не перечислением руками")
    # Предметы судьи и их состояния. Ожидание — НАМЕРЕНИЕ (что судья обязан ответить), а не
    # вывод из его же кода: иначе таблица зеленела бы на сломанном судье.
    REGISTRY_STATE = {
        "нет":     None,
        "пустой":  снимок("сдвиг-разметки"),
        "строки":  снимок(),
    }
    # Пол считается ЗАМЕРОМ снимка, а не пишется цифрой: зашитое число сгниёт на первой же
    # находке в реестре, и таблица начнёт судить не то, что называет.
    строк = int(замер(REGISTRY_STATE["строки"]))
    FLOOR_STATE = {"нет": None, "нечитаем": "не число", "число": str(строк)}
    ROWS_REL = {"меньше": str(строк + 1), "ровно": str(строк), "больше": str(строк - 1)}
    FLAGS = ("--check", "--bless")

    def intent(reg: str, flo: str, rel: str | None, flag: str) -> int:
        """Что судья ОБЯЗАН ответить. Пишется намерением, читается как требование."""
        if reg in ("нет", "пустой"):
            return 2                                   # улики нет — до флагов и до пола
        if flag == "--bless":
            return 0                                   # поднятие пола не судит
        if flo in ("нет", "нечитаем"):
            return 2                                   # храповик без пола молчать не смеет
        return 1 if rel == "меньше" else 0

    space, surprises = 0, []
    for reg, text in REGISTRY_STATE.items():
        for flo, floor_raw in FLOOR_STATE.items():
            rels = ROWS_REL if (reg == "строки" and flo == "число") else {None: floor_raw}
            for rel, floor_value in rels.items():
                for flag in FLAGS:
                    space += 1
                    code, out, err = run(text, floor_value, flag)
                    want = intent(reg, flo, rel, flag)
                    if code != want:
                        surprises.append(f"реестр={reg} пол={flo} строк={rel} {flag}: "
                                         f"ждали {want}, судья ответил {code}")
    ok(not surprises, f"обойдено сочетаний: {space}; расхождений с намерением: {len(surprises)}")
    for s in surprises:
        print(f"      · {s}")
    ok(space >= 22, f"пространство перечислено целиком, а не выборкой: {space}")

    print(f"\nПроверок: {_checks}, провалов: {len(_fails)}")
    for fail in _fails:
        print(f"  ✗ {fail}")
    return 1 if _fails else 0


if __name__ == "__main__":
    sys.exit(main())
