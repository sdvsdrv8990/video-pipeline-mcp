"""tests/quick/test_text_only.py — сам сторож `scripts/guards/text_only.py` на подставных парах ревизий.

Обе стороны каждой проверки: что обязан признать правкой текста и что обязан назвать правкой КОДА.
Живого git здесь нет намеренно — предмет сторожа это поток токенов, а не способ достать вторую
ревизию; способ судится приёмкой самого git, не нами.
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "scripts" / "guards"))

import _tokens as T  # noqa: E402 — импорт после правки sys.path: источник улики лежит у сторожей

_checks = 0
_fails: list[str] = []


def ok(cond, msg):
    global _checks
    _checks += 1
    if not cond:
        _fails.append(msg)
    print(f"  {'✓' if cond else '✗'} {msg}")


БЫЛО = '"""шапка модуля."""\nx = dict(a=1)\nif not x:\n    pass\n'

print("§1 правка ТЕКСТА поток токенов не двигает")
ok(T.разошлось(БЫЛО, '"""шапка, переписанная длиннее и иначе."""\nx = dict(a=1)\nif not x:\n    pass\n') == (0, ""),
   "§1 переписанная шапка — правка текстовая")
ok(T.разошлось(БЫЛО, БЫЛО.replace("x = dict(a=1)", "x = dict(a=1)  # пояснение")) == (0, ""),
   "§1 добавленный комментарий — правка текстовая")

print("§2 съеденный шапкой оператор — правка КОДА, и набор этого не покажет")
сдвиг, чем = T.разошлось(БЫЛО, '"""шапка."""\nif not x:\n    pass\n')
ok(сдвиг and "было 'x'" in чем, "§2 потеря названа словами, а не одним числом")

print("§3 подмена литерала в КОДЕ текстовой правкой НЕ считается")
сдвиг, чем = T.разошлось(БЫЛО, БЫЛО.replace("a=1", "a=2"))
ok(сдвиг and "'1'" in чем and "'2'" in чем, "§3 значение в коде — правка кода, а не текст")

print("§4 битый текст даёт «улики нет», а не «токенов ноль»")
ok(T.поток("def f(:\n") == [], "§4 неразбираемое не выдаётся за пустой файл")

print("§5 докстринг отличается от строки-значения ПОЛОЖЕНИЕМ, а не кавычками")
ok(T.разошлось('def f():\n    """док."""\n    return "значение"\n',
               'def f():\n    """другой док."""\n    return "значение"\n') == (0, ""),
   "§5 правка докстринга функции — текстовая")
сдвиг, _ = T.разошлось('def f():\n    """док."""\n    return "значение"\n',
                       'def f():\n    """док."""\n    return "другое"\n')
ok(сдвиг == 1, "§5 правка возвращаемой строки — правка КОДА")

print(f"\nПроверок: {_checks}, провалов: {len(_fails)}")
if _fails:
    for f in _fails:
        print(f"  - {f}")
    sys.exit(1)
