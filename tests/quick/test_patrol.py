"""
tests/quick/test_patrol.py — единый словарь улик и наряд, обе стороны.

Standalone-прогон:  python tests/quick/test_patrol.py
Проверяет `scripts/guards/_evidence.py` и `scripts/guards/patrol.py` на ПОДСТАВНОМ объявлении:
род выводится из тронутого файла, частная улика раскрывается в главную, набор поднимается по
росписи, а улика, не поднявшая никого, названа находкой, а не тишиной. Боевое объявление здесь
не участвует — набор, зависящий от состояния живого дерева, падает в любом свежем.
"""
import contextlib
import io
import sys
import tempfile
from pathlib import Path
from types import ModuleType

ROOT = Path(__file__).resolve().parents[2]
GUARDS = ROOT / "scripts" / "guards"
sys.path.insert(0, str(GUARDS))
sys.dont_write_bytecode = True


def _load(path: Path, name: str):
    """Компиляция ИЗ ИСХОДНИКА: кэш байткода признаёт свежим .pyc при том же размере и секунде."""
    module = ModuleType(name)
    module.__file__ = str(path)
    exec(compile(path.read_text(encoding="utf-8"), str(path), "exec"), module.__dict__)
    return module


улики = _load(GUARDS / "_evidence.py", "_evidence")
sys.modules["_evidence"] = улики
sys.modules["_verdict"] = _load(GUARDS / "_verdict.py", "_verdict")
наряд = _load(GUARDS / "patrol.py", "patrol")

_checks = 0
_fails = []

ОБЪЯВЛЕНИЕ = """главные:
  чтение: {про: посмотрели, видно: Read}
  редактирование: {про: изменили существующее, видно: Edit}
  создание: {про: завели новый файл, видно: Write}
роды:
  правка-сервера: {главная: редактирование, про: тронуто дерево сервера, когда: ["*.py"]}
  красный-суд: {главная: чтение, про: читаем запись отказа, когда: []}
сторожа:
  первый.py: {улики: [редактирование], команда: ["--check"], авто: хук}
  второй.py: {улики: [редактирование, создание], команда: ["--суд"], авто: нет}
  третий.py: {улики: [чтение], команда: [], авто: гейт поставки}
"""


def ok(cond, msg):
    global _checks
    _checks += 1
    if not cond:
        _fails.append(msg)
    print(f"  {'✓' if cond else '✗'} {msg}")


def объявление(текст: str = ОБЪЯВЛЕНИЕ, имя: str = "evidence.yaml") -> Path:
    дом = Path(tempfile.mkdtemp(prefix="vpm_patrol_"))
    (дом / имя).write_text(текст, encoding="utf-8")
    return дом / имя


def main() -> int:
    print("=== словарь улик: три главные и привязка к ним ===")
    путь = объявление()
    ok(sorted(улики.главные(путь)) == ["редактирование", "создание", "чтение"],
       "три главные улики читаются из объявления, а не зашиты в код")
    ok(улики.rods_of(["core/x.py"], путь) == ["правка-сервера"],
       "род выводится из ТРОНУТОГО файла — спрашивать его у правщика значит верить на слово")
    ok(not улики.rods_of(["README.md"], путь),
       "файл не подходит ни под один род — молчим, а не выдумываем улику")
    ok(улики.main_of("правка-сервера", путь) == "редактирование",
       "частный род привязан к главной улике: по ней и поднимается набор")
    ok(улики.expand(["правка-сервера", "создание"], путь) == ["редактирование", "создание"],
       "смесь частных и главных разворачивается в главные — единственный ключ росписи")
    ok(not улики.роды(путь.with_name("нет.yaml")),
       "объявления нет вовсе — улики нет, а не пустой ответ, выдающий себя за полный")

    print("\n=== наряд: кого поднимает улика ===")
    ok([и for и, _ in улики.наряд(["редактирование"], путь)] == ["второй.py", "первый.py"],
       "на редактирование отзываются оба объявленных сторожа")
    ok([и for и, _ in улики.наряд(["правка-сервера"], путь)] == ["второй.py", "первый.py"],
       "частная улика поднимает тот же набор, что её главная")
    ok([и for и, _ in улики.наряд(["создание"], путь)] == ["второй.py"],
       "на создание отзывается только объявленный на него")
    ok(not улики.наряд(["чтение"], путь),
       "сторож без команды вручную не поднимается — объявление говорит об этом прямо")

    print("\n=== два режима: сухой ход и незнакомая улика ===")
    наряд._evidence.DECL = путь
    буфер = io.StringIO()
    with contextlib.redirect_stdout(буфер):
        код = наряд.main(["--кто", "--улика", "создание"])
    печать = буфер.getvalue()
    ok(код == 0 and "второй.py --суд" in печать and "первый.py" not in печать,
       "сухой ход называет ТОЛЬКО отозвавшихся и ничего не запускает")
    ошибка = io.StringIO()
    with contextlib.redirect_stderr(ошибка), contextlib.redirect_stdout(io.StringIO()):
        код = наряд.main(["--улика", "выдуманная"])
    ok(код == 2 and "не объявлена" in ошибка.getvalue(),
       "улика не из словаря — отказ с перечнем известных, а не молчаливый пустой наряд")
    наряд._evidence.DECL = объявление(
        "главные: {чтение: {про: п, видно: в}}\nроды: {}\nсторожа: {}\n", "пусто.yaml")
    буфер = io.StringIO()
    with contextlib.redirect_stdout(буфер):
        код = наряд.main(["--улика", "чтение"])
    ok(код == 1 and "не отзывается никто" in буфер.getvalue(),
       "улика, не поднявшая никого, названа находкой — иначе пустой наряд читается как «чисто»")

    print(f"\nПроверок: {_checks}, провалов: {len(_fails)}")
    for fail in _fails:
        print(f"  ✗ {fail}")
    return 1 if _fails else 0


if __name__ == "__main__":
    sys.exit(main())
