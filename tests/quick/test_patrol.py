"""
tests/quick/test_patrol.py — единый словарь улик и наряд, обе стороны.

Standalone-прогон:  python tests/quick/test_patrol.py
Проверяет `scripts/guards/_evidence.py` и `scripts/guards/patrol.py` на ПОДСТАВНОМ объявлении:
род выводится из тронутого файла, частная улика раскрывается в главную, набор поднимается по
росписи, а улика, не поднявшая никого, названа находкой, а не тишиной. Боевое объявление здесь
не участвует — набор, зависящий от состояния живого дерева, падает в любом свежем.
"""
import contextlib
import io
import os
import sys
import tempfile
from pathlib import Path
from types import ModuleType

ROOT = Path(__file__).resolve().parents[2]
GUARDS = ROOT / "scripts" / "guards"
sys.path.insert(0, str(GUARDS))
sys.dont_write_bytecode = True


def _load(path: Path, name: str):
    """Компиляция ИЗ ИСХОДНИКА: кэш байткода признаёт свежим .pyc при том же размере и секунде."""
    module = ModuleType(name)
    module.__file__ = str(path)
    exec(compile(path.read_text(encoding="utf-8"), str(path), "exec"), module.__dict__)
    return module


улики = _load(GUARDS / "_evidence.py", "_evidence")
sys.modules["_evidence"] = улики
sys.modules["_verdict"] = _load(GUARDS / "_verdict.py", "_verdict")
наряд = _load(GUARDS / "patrol.py", "patrol")

_checks = 0
_fails = []

ОБЪЯВЛЕНИЕ = """главные:
  чтение: {про: посмотрели, видно: Read}
  редактирование: {про: изменили существующее, видно: Edit}
  создание: {про: завели новый файл, видно: Write}
роды:
  правка-сервера: {главная: редактирование, про: тронуто дерево сервера, когда: ["*.py"]}
  красный-суд: {главная: чтение, про: читаем запись отказа, когда: []}
сторожа:
  первый.py: {улики: [редактирование], команда: ["--check"], авто: хук}
  второй.py: {улики: [редактирование, создание], команда: ["--суд"], авто: нет}
  третий.py: {улики: [чтение], команда: [], авто: гейт поставки}
  точный.py: {улики: [правка-сервера], команда: ["--суд"], авто: нет}
задачи:
  правка-сервера:
    улики: [правка-сервера]
    сверх: {первый.py: ["--affected"]}
    скил: mcp-developer
    про: тронуто дерево сервера
хуки:
  vpm-первый.py: {улики: [редактирование], событие: PreToolUse, про: п}
  vpm-второй.py: {улики: [редактирование, создание], событие: PostToolUse, про: п}
  vpm-конец.py: {улики: [], событие: Stop, про: граница сессии}
"""


def ok(cond, msg):
    global _checks
    _checks += 1
    if not cond:
        _fails.append(msg)
    print(f"  {'✓' if cond else '✗'} {msg}")


def объявление(текст: str = ОБЪЯВЛЕНИЕ, имя: str = "evidence.yaml") -> Path:
    дом = Path(tempfile.mkdtemp(prefix="vpm_patrol_"))
    (дом / имя).write_text(текст, encoding="utf-8")
    return дом / имя


def main() -> int:
    print("=== словарь улик: три главные и привязка к ним ===")
    путь = объявление()
    ok(sorted(улики.главные(путь)) == ["редактирование", "создание", "чтение"],
       "три главные улики читаются из объявления, а не зашиты в код")
    ok(улики.rods_of(["core/x.py"], путь) == ["правка-сервера"],
       "род выводится из ТРОНУТОГО файла — спрашивать его у правщика значит верить на слово")
    ok(not улики.rods_of(["README.md"], путь),
       "файл не подходит ни под один род — молчим, а не выдумываем улику")
    ok(улики.main_of("правка-сервера", путь) == "редактирование",
       "частный род привязан к главной улике: по ней и поднимается набор")
    ok(улики.expand(["правка-сервера", "создание"], путь) == ["редактирование", "создание"],
       "смесь частных и главных разворачивается в главные — единственный ключ росписи")
    ok(not улики.роды(путь.with_name("нет.yaml")),
       "объявления нет вовсе — улики нет, а не пустой ответ, выдающий себя за полный")

    print("\n=== наряд: кого поднимает улика ===")
    ok([и for и, _ in улики.наряд(["редактирование"], путь)] == ["второй.py", "первый.py"],
       "на редактирование отзываются оба объявленных сторожа")
    ok([и for и, _ in улики.наряд(["правка-сервера"], путь)] == ["второй.py", "первый.py", "точный.py"],
       "частная улика поднимает набор своей главной И сторожей, объявленных на неё саму")
    ok([и for и, _ in улики.наряд(["создание"], путь)] == ["второй.py"],
       "на создание отзывается только объявленный на него")
    ok(not улики.наряд(["чтение"], путь),
       "сторож без команды вручную не поднимается — объявление говорит об этом прямо")

    print("\n=== два режима: сухой ход и незнакомая улика ===")
    наряд._evidence.DECL = путь
    буфер = io.StringIO()
    with contextlib.redirect_stdout(буфер):
        код = наряд.main(["--кто", "--улика", "создание"])
    печать = буфер.getvalue()
    ok(код == 0 and "второй.py --суд" in печать and "первый.py" not in печать,
       "сухой ход называет ТОЛЬКО отозвавшихся и ничего не запускает")
    ошибка = io.StringIO()
    with contextlib.redirect_stderr(ошибка), contextlib.redirect_stdout(io.StringIO()):
        код = наряд.main(["--улика", "выдуманная"])
    ok(код == 2 and "не объявлена" in ошибка.getvalue(),
       "улика не из словаря — отказ с перечнем известных, а не молчаливый пустой наряд")
    наряд._evidence.DECL = объявление(
        "главные: {чтение: {про: п, видно: в}}\nроды: {}\nсторожа: {}\n", "пусто.yaml")
    буфер = io.StringIO()
    with contextlib.redirect_stdout(буфер):
        код = наряд.main(["--улика", "чтение"])
    ok(код == 1 and "не отзывается никто" in буфер.getvalue(),
       "улика, не поднявшая никого, названа находкой — иначе пустой наряд читается как «чисто»")

    print("=== точность выбора: сторож на РОД не поднимается на чужую правку ===")
    путь = объявление()
    поднятые = dict(улики.наряд(["правка-сервера"], путь))
    ok("точный.py" in поднятые and "первый.py" in поднятые,
       "на род поднимается и сторож рода, и сторож его главной улики")
    ok("точный.py" not in dict(улики.наряд(["создание"], путь)),
       "сторож, объявленный на РОД, на чужую улику не зовётся — ложный вызов выключает сторожа целиком")

    print("=== выбор сторожей по ТИПУ РАБОТЫ ===")
    буфер = io.StringIO()
    наряд._evidence.DECL = путь
    with contextlib.redirect_stdout(буфер):
        код = наряд.main(["--задача", "правка-сервера"])
    отчёт = буфер.getvalue()
    ok(код == 0 and "первый.py --affected (сверх авто)" in отчёт,
       "тип работы называет сторожа СВЕРХ тех, кого поднимет улика")
    ok("mcp-developer" in отчёт and "проснутся" in отчёт,
       "разбор задачи ведёт и в скил, и в список тех, кого разбудит событие")
    ошибка = io.StringIO()
    with contextlib.redirect_stderr(ошибка), contextlib.redirect_stdout(io.StringIO()):
        код = наряд.main(["--задача", "выдуманная"])
    ok(код == 2 and "не объявлен" in ошибка.getvalue(),
       "неизвестный тип работы — отказ с перечнем известных, а не пустой разбор")

    print("=== факт срабатывания: кто ОБЯЗАН был сработать и сработал ли ===")
    путь = объявление()
    ok(улики.ожидаются(["редактирование"], путь) == ["vpm-второй.py", "vpm-первый.py"],
       "по улике названы хуки, которых будит событие, — а не только сторожа наряда")
    ok(улики.ожидаются(["создание"], путь) == ["vpm-второй.py"],
       "у каждой главной улики свой набор обязанных: списки не совпадают")
    ok(улики.ожидаются(["чтение"], путь) == [],
       "на «чтение» не встаёт ни один хук — Read события не даёт, и это утверждение, а не пропуск")
    ok(улики.ожидаются(["правка-сервера"], путь) == ["vpm-второй.py", "vpm-первый.py"],
       "частный род раскрывается в главную и там уже спрашивает хуков")
    ok("vpm-конец.py" not in улики.ожидаются(["редактирование", "создание", "чтение"], путь),
       "сторож границы сессии ни по какой улике не ожидается: он стоит не на дереве")

    # Сам разбор следа: подставной каталог, чтобы набор не зависел от того, что делали в машине.
    трасса = _load(ROOT / ".claude" / "hooks" / "_trace.py", "_trace")
    sys.modules["_trace"] = трасса
    os.environ["HOME"] = tempfile.mkdtemp(prefix="vpm_patrol_дом_")
    трасса.mark("vpm-первый.py")
    # Отметка обязана лечь в ПОДСТАВНОЙ дом: путь, связанный в объявлении, писал бы и читал
    # боевой след — набор бы прошёл, а живой след получил бы выдуманного сторожа.
    ok((Path(os.environ["HOME"]) / ".claude" / "state" / "vpm-trace" / "vpm-первый.py.json").exists(),
       "след пишется в дом, подставленный ПОСЛЕ загрузки модуля: путь разрешается в момент вызова")
    наряд._evidence.DECL = путь
    буфер = io.StringIO()
    with contextlib.redirect_stdout(буфер):
        код = наряд.main(["--факт", "--улика", "редактирование"])
    отчёт = буфер.getvalue()
    ok(код != 0 and "vpm-второй.py" in отчёт and "промолчали" in отчёт,
       "молчание обязанного хука — отказ с именем: это пропуск срабатывания, а не «чисто»")
    ok("✓ vpm-первый.py" in отчёт, "сработавший назван отдельно от промолчавшего")
    буфер = io.StringIO()
    with contextlib.redirect_stdout(буфер):
        код = наряд.main(["--факт", "--улика", "редактирование", "--за", "0"])
    ok(код != 0 and "vpm-первый.py" in буфер.getvalue(),
       "вчерашняя отметка про сегодняшнюю работу не говорит ничего: окно судит свежесть")

    print(f"\nПроверок: {_checks}, провалов: {len(_fails)}")
    for fail in _fails:
        print(f"  ✗ {fail}")
    return 1 if _fails else 0


if __name__ == "__main__":
    sys.exit(main())
