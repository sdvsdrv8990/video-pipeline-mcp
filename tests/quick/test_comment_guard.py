# ── ЧИТАТЕЛЬ дома: сторож дерева обязан снимать замечание с долга и НАЗЫВАТЬ зону ─────────────
import contextlib as _ctx                  # noqa: E402 — блок дописан к готовому набору
import io as _io  # noqa: E402 — там же


def _суд(зоны_ответ, замечания=None):
    """Прогон `--check` на подставленных замечаниях и подставленном доме: дерево не трогаем."""
    было_collect, было_потолок, было_зоны = G.collect, G._load_baseline, C.зоны
    G.collect = lambda targets=None: замечания if замечания is not None else {"core/жив.py": ["мусор"]}
    G._load_baseline = lambda: {}
    C.зоны = lambda *а, **к: зоны_ответ
    буфер = _io.StringIO()
    try:
        with _ctx.redirect_stdout(буфер):
            код = G.cmd_check()
    finally:
        G.collect, G._load_baseline, C.зоны = было_collect, было_потолок, было_зоны
    return код, буфер.getvalue()


