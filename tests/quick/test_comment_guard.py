def _дерево(строки: str, *, ключ: str | None = None, файл: str = "core/жив.py"):
    """Подставное дерево: дом исключений, журнал подписей и файл зоны. Машинонезависимо."""
    корень = Path(_tmp.mkdtemp(prefix="vpm-искл-"))
    (корень / "scripts" / "guards").mkdir(parents=True)
    (корень / "scripts" / "guards" / "comment_exceptions.yaml").write_text(строки, encoding="utf-8")
    (корень / Path(файл).parent).mkdir(parents=True, exist_ok=True)
    (корень / файл).write_text("x = 1\n", encoding="utf-8")
    журнал = корень / "tests" / ".journal"
    журнал.mkdir(parents=True)
    if ключ:
        запись = {"key": ключ, "kind": "гейт", "role": "РЕШЕНИЕ", "what": "зона объявлена"}
