"""scripts/guards/_comments.py — источник улики: где комментарий объявлен исключением и до какого срока.

Зовёт: _stamp.
Зовут: comment_guard, vpm-comment-intent.

Не судит и кода возврата не даёт. Отвечает на два вопроса: какие зоны действуют и какие строки
объявления незаконны. Незаконная возвращается претензией, а не пропускается: дом без отказа стал бы
лазейкой, и «объявил исключение» превратилось бы в слово.

Право объявлять зону у ВЛАДЕЛЬЦА: ключ его подписи обязан поднимать запись в общем журнале тем же
`_stamp.find`, которым её поднимает производитель сценариев. Срок обязателен — вечное исключение есть
снятая проверка; истёкшая зона не отказ, она просто перестаёт покрывать.
"""

from __future__ import annotations

import datetime as dt
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
ДОМ = ("scripts", "guards", "comment_exceptions.yaml")
КЛАССЫ = ("плавающий-дефект", "передача-человеку")
ПОЛЯ = ("зона", "класс", "почему", "подпись", "до")


def _поднимается(ключ: str, root: Path) -> bool:
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    import _stamp
    return bool(_stamp.find(ключ, root))


def _вердикт(строка: dict, root: Path, сегодня: dt.date) -> tuple[str, str]:
    """Состояние одной строки и причина, если она не действует."""
    нет = [поле for поле in ПОЛЯ if not str(строка.get(поле) or "").strip()]
    if нет:
        return "незаконна", f"нет обязательных полей: {', '.join(нет)}"
    if строка["класс"] not in КЛАССЫ:
        return "незаконна", f"класс `{строка['класс']}` не из объявленных: {', '.join(КЛАССЫ)}"
    if not (root / str(строка["зона"])).exists():
        return "незаконна", f"пути `{строка['зона']}` на диске нет — зона указывает в пустоту"
    if not _поднимается(str(строка["подпись"]), root):
        return "незаконна", f"подпись `{строка['подпись']}` не поднимается — ключ обязан вести к записи"
    try:
        срок = dt.date.fromisoformat(str(строка["до"]))
    except ValueError:
        return "незаконна", f"срок `{строка['до']}` не читается как дата (ГГГГ-ММ-ДД)"
    if срок < сегодня:
        return "истекла", f"срок вышел {срок.isoformat()} — зона больше не покрывает"
    return "действует", ""


def зоны(root: Path = ROOT, сегодня: dt.date | None = None) -> list[dict]:
    """Строки дома с вердиктом по каждой. Дома нет — исключений не объявлено, и это не беда."""
    дом = root.joinpath(*ДОМ)
    if not дом.is_file():
        return []
    объявлено = yaml.safe_load(дом.read_text(encoding="utf-8")) or []
    сегодня = сегодня or dt.date.today()
    ответ = []
    for строка in объявлено:
        if not isinstance(строка, dict):
            ответ.append({"зона": str(строка), "состояние": "незаконна",
                          "почему_нет": "строка объявления не отображение"})
            continue
        состояние, причина = _вердикт(строка, root, сегодня)
        ответ.append({**строка, "состояние": состояние, "почему_нет": причина})
    return ответ


def покрыт(rel: str, объявленные: list[dict] | None = None, root: Path = ROOT) -> dict | None:
    """Действующая зона, накрывающая этот путь, либо `None`. Каталог накрывает файлы под ним."""
    for зона in (объявленные if объявленные is not None else зоны(root)):
        if зона.get("состояние") != "действует":
            continue
        предмет = str(зона.get("зона") or "")
        if предмет and (rel == предмет or rel.startswith(предмет.rstrip("/") + "/")):
            return зона
    return None


def претензии(объявленные: list[dict] | None = None, root: Path = ROOT) -> list[str]:
    """Незаконные строки дома: читатель ОБЯЗАН их печатать, иначе дом станет лазейкой."""
    return [f"дом исключений: зона `{з.get('зона')}` не действует — {з.get('почему_нет')}"
            for з in (объявленные if объявленные is not None else зоны(root))
            if з.get("состояние") == "незаконна"]
