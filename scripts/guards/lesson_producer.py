#!/usr/bin/env python3
"""scripts/guards/lesson_producer.py — из подписи прогона рождается заготовка урока.

Не сторож: ничего не запрещает и вердикта не выносит. Отвечает на вопрос, который до сих пор
решался памятью автора, — что здесь можно записать уроком, чем он ловится и при каких условиях
повторяется.

Каждый свой этап производитель РАСПИСЫВАЕТ: условия набором, исход, причину и следствие. Молчание
записывается наравне со срабатыванием и называет ложное условие — иначе тишина неотличима от
отсутствия механизма. Отсюда считается цена шага (`--свод`: какой шаг ни разу не срабатывал) и
берутся условия самой заготовки: они выводятся из набора прогона, а не сочиняются словами.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(Path(__file__).resolve().parent))

import _stamp  # noqa: E402 — дорога к соседям кладётся строкой выше

# Признаки материала для урока. НАБОР, а не один очевидный признак: отказ, скрытый риск и
# несбывшееся ожидание — разные болезни, и каждая учит своему.
ПРИЗНАКИ = (
    ("роль записи говорит об отказе", lambda з: з.get("role") in ("ОТКАЗ", "ОСТАТОК")),
    ("в факте назван скрытый риск", lambda з: _число(з.get("actual", ""), "риска") > 0),
    ("заявленное не сбылось", lambda з: _число(з.get("actual", ""), "не сбылось") > 0),
)


def _число(текст: str, метка: str) -> int:
    """Число после метки в строке факта; нет метки — ноль, а не догадка."""
    части = текст.split(метка, 1)
    if len(части) < 2:
        return 0
    хвост = части[1].strip().split(" ", 1)[0].strip(" ·,")
    return int(хвост) if хвост.isdigit() else 0


def _разошедшиеся(запись: dict) -> list[str]:
    """Метки проверок, сменивших цвет незаявленно или не сбывшихся. Их называет сама запись."""
    подробно = запись.get("detail") or {}
    метки = []
    for поле in ("риск", "не сбылось"):
        for строка in подробно.get(поле) or []:
            метки.append(str(строка[0]) if isinstance(строка, list) and строка else str(строка))
    return [м for м in метки if м.strip()]


def _оси_с_нарушением(запись: dict) -> list[str]:
    """Оси, у которых в этом прогоне нашлось больше потолка. Числа лежат в самой записи."""
    оси = ((запись.get("detail") or {}).get("оси") or {})
    return [имя for имя, поля in оси.items()
            if isinstance(поля, dict) and поля.get("нашёл", 0) > поля.get("потолок", 0)]


def ловец(запись: dict, root: Path = ROOT) -> tuple[str, list[dict]]:
    """(метка исполнителя, набор условий её поиска).

    Источника два, и они АЛЬТЕРНАТИВЫ: разошедшаяся проверка (её называет цикл) и ось, перешедшая
    потолок (её называет гейт). Метку ищем в записи, а не в строке команды: команда называет
    ЗАПУСКАЕМОЕ, а ловцом урока служит то, что покраснеет при повторе ошибки.
    """
    проверки, оси = _разошедшиеся(запись), _оси_с_нарушением(запись)
    метка = (f"проверка «{проверки[0]}»" if проверки
             else f"ось `{оси[0]}`" if оси else "")
    условия = [
        _stamp.условие("запись называет разошедшуюся проверку", True, bool(проверки), решает=False),
        _stamp.условие("запись называет ось за потолком", True, bool(оси), решает=False),
        _stamp.условие("ловец найден хоть одним источником", True, bool(метка)),
    ]
    return метка, условия


def произвести(ключ: str, root: Path = ROOT) -> tuple[list[dict], str]:
    """Цепочка шагов и заготовка урока. Заготовки нет, если хоть один шаг промолчал."""
    шаги: list[dict] = []
    предыдущий = ""
    повтор = f".venv/bin/python scripts/guards/lesson_producer.py --stamp {ключ}"

    def расписать(имя: str, механизм: str, условия: list[dict], следствие: str) -> bool:
        nonlocal предыдущий
        сошлось = all(у["сошлось"] for у in условия if у.get("решает", True))
        ключ_шага, _ = _stamp.шаг(
            имя, механизм, условия, исход="сработал" if сошлось else "молчал",
            следствие=следствие if сошлось else f"дальше не идём: {следствие}",
            прогон=ключ, предыдущий=предыдущий, cmd=повтор, зона="сторожа", root=root)
        шаги.append({"имя": имя, "исход": "сработал" if сошлось else "молчал", "ключ": ключ_шага})
        предыдущий = ключ_шага
        return сошлось

    записи = _stamp.find(ключ, root)
    журнал = list(root.joinpath(*_stamp.JOURNAL).glob("stamps-*.jsonl"))
    if not расписать("поднять запись", "_stamp.find",
                     [_stamp.условие("ключ назван", True, bool(ключ)),
                      _stamp.условие("журнал подписей есть", True, bool(журнал)),
                      _stamp.условие("запись по ключу поднята", True, bool(записи))],
                     "запись поднята" if записи else "по ключу записи нет"):
        return шаги, ""

    запись = записи[-1]
    # Признаки — АЛЬТЕРНАТИВЫ: каждый остаётся в наборе картиной, а исход решает их «хоть один».
    признаки = [_stamp.условие(имя, True, признак(запись), решает=False)
                for имя, признак in ПРИЗНАКИ]
    сошлись = [у["имя"] for у in признаки if у["сошлось"]]
    # Материал есть, если сработал ХОТЬ ОДИН признак, и каждый остаётся в наборе поимённо: иначе
    # видно «что-то разошлось» вместо того, какая именно болезнь дала урок.
    if not расписать("найти расхождение", "разбор полей записи",
                     [*признаки,
                      _stamp.условие("хоть один признак разошёлся", True, bool(сошлись))],
                     f"материал урока: {', '.join(сошлись)}" if сошлись
                     else "ожидание сошлось с фактом — урока здесь нет"):
        return шаги, ""

    метка, где_искали = ловец(запись, root)
    if not расписать("назвать механизм-ловец", "разбор записи прогона", где_искали,
                     f"ловец: {метка}" if метка
                     else "запись не называет ни разошедшейся проверки, ни оси за потолком"):
        return шаги, ""

    import invariants
    # Судья разрешает метку двумя способами, и оба берём у НЕГО, а не повторяем своим разбором.
    if метка.startswith("проверка "):
        имя_метки = метка.split("«", 1)[-1].rstrip("»")
        разрешима = имя_метки in invariants._suite_text(root)
    else:
        разрешима = метка.split("`")[1] in invariants._mechanisms(root) if "`" in метка else False
    # Заготовка, чью метку судья не прочтёт, — урок вне суда: производитель обязан спросить
    # судью, а не надеяться на него. Обратную сторону той же беды дом уроков уже пережил: судья,
    # читавший одну форму записи из двух, оставлял без суда каждый второй урок.
    if not расписать("разрешить метку исполнителя", "invariants._mechanisms",
                     [_stamp.условие("метка построена", True, bool(метка)),
                      _stamp.условие("судья метку разрешает", True, разрешима)],
                     f"метка ⟨исполняет: {метка}⟩ судится" if разрешима
                     else f"метку `{метка}` судья не разрешит"):
        return шаги, ""

    условия = "; ".join(сошлись)
    заготовка = (f"## {запись.get('what', '')[:90]} ({запись.get('head', '')})\n\n"
                 f"**Why:** ожидание было «{запись.get('expected', '')[:160]}», факт — "
                 f"«{запись.get('actual', '')[:160]}».\n"
                 f"**How to apply:** повторяется командой `{запись.get('cmd', '')}`.\n"
                 f"⟨исполняет: {метка}⟩ ⟨улика: ⟦vpm {ключ}⟧⟩ ⟨условия: {условия}⟩\n")
    расписать("выдать заготовку", "сборка трёх частей",
              [_stamp.условие("механизм назван", True, bool(метка)),
               _stamp.условие("ключ улики есть", True, bool(ключ)),
               _stamp.условие("условия выведены из набора", True, bool(условия))],
              "заготовка урока выдана")
    return шаги, заготовка


def main() -> int:
    ap = argparse.ArgumentParser(description="из подписи прогона — заготовка урока с росписью шагов")
    ap.add_argument("--stamp", help="ключ подписи прогона, из которого рождается урок")
    ap.add_argument("--шаги", help="напечатать роспись шагов этого прогона")
    ap.add_argument("--свод", action="store_true",
                    help="цена шагов: какой шаг сколько раз сработал и сколько молчал")
    args = ap.parse_args()
    if args.свод:
        свод = _stamp.молчавшие(ROOT)
        if not свод:
            print("росписи шагов нет — улики нет, а не «шагов ноль»")
            return 0
        for имя, сработал, молчал in свод:
            цена = " — НИ РАЗУ не срабатывал, кандидат на снос" if not сработал else ""
            print(f"── {имя}: сработал {сработал}, молчал {молчал}{цена}")
        return 0
    if args.шаги:
        роспись = _stamp.шаги(args.шаги, ROOT)
        if not роспись:
            print(f"по прогону {args.шаги} росписи нет — улики нет, а не «шагов ноль»")
            return 0
        for ш in роспись:
            print(f"── {ш['имя']} [{ш['исход']}] {ш['ключ']}\n   причина: {ш['причина']}\n"
                  f"   следствие: {ш['следствие']}")
            for у in ш["условия"]:
                роль = "решает" if у.get("решает", True) else "картина"
                print(f"     {'✓' if у.get('сошлось') else '✗'} [{роль}] {у['имя']}: "
                      f"ждали {у['ждали']!r}, факт {у['факт']!r}")
        return 0
    if not args.stamp:
        ap.error("нужен --stamp КЛЮЧ, либо --шаги КЛЮЧ, либо --свод")
    шаги, заготовка = произвести(args.stamp, ROOT)
    for ш in шаги:
        print(f"── {ш['имя']}: {ш['исход']} ({ш['ключ']})")
    print()
    print(заготовка if заготовка else
          "заготовки нет: цепочка остановилась, и причина записана в росписи выше (поднять: "
          f".venv/bin/python scripts/guards/lesson_producer.py --шаги {args.stamp})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
