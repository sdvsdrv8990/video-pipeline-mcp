#!/usr/bin/env python3
"""scripts/guards/_precision.py — источник улики: журнал ТОЧНОСТИ срабатываний сторожей.

След (`_trace.py`) отвечает «сколько раз и когда», но не «по делу ли». Исход не выводится из
самого срабатывания — знай хук, что ошибся, он бы не сработал, — поэтому его записывают РУКОЙ.
Журнал лежит под git рядом с потолками: вне git число невоспроизводимо между машинами.

Не судит и exit-кода не даёт.

    .venv/bin/python scripts/guards/_precision.py --хук vpm-fact-gate.py \\
        --исход ложно --что "принял чтение вывода за вердикт" --проверка "§16 test_hooks"
"""
from __future__ import annotations

import json
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ЖУРНАЛ = Path(__file__).with_name("hook_precision.jsonl")
ИСХОДЫ = ("по-делу", "ложно", "шум")


def записи(путь: Path | None = None) -> list[dict]:
    """Журнал целиком. Нет файла — пусто, а не отказ: свежий клон это не «точность идеальна»."""
    путь = путь or ЖУРНАЛ
    if not путь.exists():
        return []
    итог = []
    for строка in путь.read_text(encoding="utf-8", errors="replace").splitlines():
        if not строка.strip():
            continue
        try:
            итог.append(json.loads(строка))
        except json.JSONDecodeError:
            continue
    return итог


def записать(хук: str, исход: str, что: str, проверка: str = "",
             путь: Path | None = None) -> dict:
    """Добавить исход срабатывания. Исход из объявленных — иначе вокабуляр расползётся словами."""
    if исход not in ИСХОДЫ:
        raise ValueError(f"исход `{исход}` не объявлен; известны {list(ИСХОДЫ)}")
    if not что.strip():
        raise ValueError("исход без описания не улика: назови, ЧТО именно сработало не так")
    запись = {"хук": хук, "исход": исход, "что": что.strip(),
              "проверка": проверка.strip(), "ts": time.time()}
    путь = путь or ЖУРНАЛ
    with путь.open("a", encoding="utf-8") as f:
        f.write(json.dumps(запись, ensure_ascii=False) + "\n")
    return запись


def точность(путь: Path | None = None) -> dict[str, dict]:
    """Число на хук: сколько по делу, сколько ложных, сколько шума и какова доля точных."""
    итог: dict[str, dict] = {}
    for запись in записи(путь):
        строка = итог.setdefault(запись.get("хук", "?"),
                                 {исход: 0 for исход in ИСХОДЫ} | {"без-проверки": 0})
        исход = запись.get("исход")
        if исход in ИСХОДЫ:
            строка[исход] += 1
        if исход == "ложно" and not (запись.get("проверка") or "").strip():
            строка["без-проверки"] += 1
    for строка in итог.values():
        всего = sum(строка[исход] for исход in ИСХОДЫ)
        строка["точность"] = round(строка["по-делу"] / всего, 2) if всего else 0.0
    return итог


def ложные_без_проверки(путь: Path | None = None) -> list[str]:
    """Ложные срабатывания, за которыми не закреплена проверка, — долг, который повторится."""
    return [f"{з.get('хук', '?')}: {з.get('что', '')}"
            for з in записи(путь)
            if з.get("исход") == "ложно" and not (з.get("проверка") or "").strip()]


def _значение(argv: list[str], флаг: str) -> str:
    return argv[argv.index(флаг) + 1] if флаг in argv and len(argv) > argv.index(флаг) + 1 else ""


def main() -> int:
    argv = sys.argv[1:]
    if "--хук" in argv:
        запись = записать(_значение(argv, "--хук"), _значение(argv, "--исход"),
                          _значение(argv, "--что"), _значение(argv, "--проверка"))
        закреплено = запись["проверка"] or "НЕТ — это долг, ось его поднимет"
        print(f"записан исход `{запись['исход']}` у {запись['хук']}; проверка: {закреплено}")
        return 0
    свод = точность()
    if not свод:
        print("журнал точности пуст: исходы срабатываний ещё не записывали")
        return 0
    for хук, строка in sorted(свод.items()):
        print(f"  {хук:26} по делу {строка['по-делу']:3} · ложно {строка['ложно']:3} · "
              f"шум {строка['шум']:3} · точность {строка['точность']:.0%} · "
              f"без проверки {строка['без-проверки']}")
    долг = ложные_без_проверки()
    print(f"\nложных без проверки в наборе: {len(долг)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
