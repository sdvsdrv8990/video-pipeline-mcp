#!/usr/bin/env python3
"""scripts/guards/_verdict.py — единый хвост суда: один журнал и один словарь на всех сторожей.

Зовёт: _routes, _stamp.
Зовут: _acceptance, comment_guard, invariants, findings_count, blast_radius, patrol.

Судья заканчивает работу одинаково, чем бы он ни судил: называет задетые правкой потоки данных и
подписывает вердикт в общий журнал — род `гейт`, роль `ВЕРДИКТ` на чистом и `ОТКАЗ` на красном. Без
подписи вердикт живёт до закрытия терминала, и «прогон был зелёный» снова становится словом.

Роль `УЛИКА` отсюда недостижима намеренно: её подписи считает гейт поставки, и сторож, подписавшийся
уликой, удовлетворял бы гейт собственным прогоном. Производители сюда не ходят — вердикта они не
выносят; судья, не зовущий этот хвост, — находка оси «судья мимо общего журнала».
"""
from __future__ import annotations

import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import _routes                                                             # noqa: E402
import _stamp                                                              # noqa: E402

ROOT = Path(__file__).resolve().parents[2]


def touched(root: Path = ROOT) -> list[str]:
    """Тронутое в дереве по `git status`: правка скриптом события не порождает, а рубеж задевает."""
    done = subprocess.run(["git", "status", "--porcelain"], cwd=root,
                          capture_output=True, text=True)
    return [line[3:].strip().split(" -> ")[-1] for line in done.stdout.splitlines() if line[3:]]


def flows(paths: list[str], root: Path = ROOT) -> list[str]:
    """Что течёт через тронутый рубеж — ЗНАНИЕ судьи, а не его вердикт.

    Правка рубежа нарушением не является; молчание о ней является: правящий не узнаёт, что через
    место течёт значение до клиента и чем это видно.
    """
    return _routes.lines(paths, root=root)


УЛИКИ = ("есть", "нет")


def роспись(сторож: str, нарушений: int, точный: bool, улика: str, причина_молчания: str) -> dict:
    """Роспись прогона судьи НАБОРОМ условий: состояние улики, исход, причина, следствие.

    Раньше запись судьи несла имя и число — по ней нельзя было отличить «смотрел и чисто» от
    «смотреть было не на что» и нельзя было сказать, ЧТО именно сделало исход таким. Состояние
    объявляет сам судья: `улика="нет"` значит, что источника не было, и тогда ноль находок
    перестаёт читаться чистотой.
    """
    if улика and улика not in УЛИКИ:
        raise ValueError(f"состояние улики `{улика}` не объявлено; известны {list(УЛИКИ)}")
    if улика == "нет" and нарушений:
        raise ValueError(f"судья нашёл {нарушений} и говорит, что источника не было: находки "
                         f"доказывают обратное, и такая запись объясняла бы любой исход")
    # Находки САМИ доказывают, что источник читался: требовать объявления у КРАСНОГО прогона
    # значило бы ронять судью на его же вердикте — поймано циклом `⟦vpm 4edc⟧` на живых наборах.
    состояние = улика or ("есть" if нарушений else "не объявлено")
    следствие = (f"названо нарушений: {нарушений}" if нарушений and точный else
                 "красный по коду возврата" if нарушений else
                 причина_молчания or ("смотрел — нарушений нет" if улика == "есть" else
                                      "молчит, а состояние улики не объявлено"))
    условия = [_stamp.условие("источник улики доступен", "есть", состояние),
               _stamp.условие("нарушение в дереве", "есть", "есть" if нарушений else "нет")]
    return _stamp.строка_шага(сторож, "сторож", условия,
                              исход="сработал" if нарушений else "молчал", следствие=следствие)


def stamp(сторож: str, нарушений: int, потоки: list[str], команда: str,
          root: Path = ROOT, точный: bool = True, детали: dict | None = None,
          улика: str = "", почему_молчит: str = "") -> str:
    """Подпись вердикта в общий журнал. Роль выводится из ЧИСЛА находок, а не из слов сторожа.

    `точный=False` означает, что судья держит только код возврата и числа находок у него нет:
    журнал говорит об этом прямо, иначе «1» читалось бы как «одно нарушение», хотя их было три.
    """
    роль = "ОТКАЗ" if нарушений else "ВЕРДИКТ"
    итог = (f"{нарушений} нарушений" if точный else "красный") if нарушений else "чисто"
    шаг = роспись(сторож, нарушений, точный, улика, почему_молчит)
    _, подпись = _stamp.sign("гейт", роль, f"{сторож}: {итог}", intent=сторож,
                             expected="прогон зелёный", actual=итог, cmd=команда,
                             detail={"сторож": сторож, "нарушений": нарушений, "потоки": потоки,
                                     "счёт": "точный" if точный else "по коду возврата",
                                     "шаг": шаг, **(детали or {})},
                             root=root)
    return подпись


def close(сторож: str, нарушений: int, команда: str, root: Path = ROOT,
          точный: bool = True, детали: dict | None = None,
          улика: str = "", почему_молчит: str = "") -> int:
    """Хвост суда, общий у всех судей: задетые потоки вслух + подпись, вердикт кодом возврата.

    `улика` — состояние судьи на ЭТОМ прогоне: «есть» (источник читался), «нет» (источника не
    было, и тогда ноль находок не чистота). Не объявлено — так и записывается: долг считает
    храповик, а не умолчание в пользу судьи.
    """
    потоки = flows(touched(root), root=root)
    print(f"── задетые потоки данных: {len(потоки) or 'нет'}")
    for строка in потоки:
        print(f"   ⇢ {строка}")
    print(stamp(сторож, нарушений, потоки, команда, root=root, точный=точный,
                детали=детали, улика=улика, почему_молчит=почему_молчит))
    return 1 if нарушений else 0
