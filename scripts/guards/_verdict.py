#!/usr/bin/env python3
"""scripts/guards/_verdict.py — единый хвост суда: один журнал и один словарь на всех сторожей.

Судья заканчивает работу одинаково, чем бы он ни судил: называет задетые правкой потоки данных
(источник улики `_routes.py`) и подписывает вердикт в общий журнал тандема (`_stamp.py`) — род
`гейт`, роль `ВЕРДИКТ` на чистом и `ОТКАЗ` на красном. Без подписи вердикт живёт до закрытия
терминала: завтра его нечем поднять, и «прогон был зелёный» снова становится словом.

Роль `УЛИКА` отсюда недостижима намеренно: её подписи считает гейт поставки, и сторож,
подписавшийся уликой, удовлетворял бы гейт собственным прогоном.

Производители (`reproduce.py`) сюда не ходят: вердикта они не выносят, и зона их так и объявлена
в `CATALOG.md`. Судья, не зовущий этот хвост, — находка оси «судья мимо общего журнала».
"""
from __future__ import annotations

import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import _routes                                                             # noqa: E402
import _stamp                                                              # noqa: E402

ROOT = Path(__file__).resolve().parents[2]


def touched(root: Path = ROOT) -> list[str]:
    """Тронутое в дереве по `git status`: правка скриптом события не порождает, а рубеж задевает."""
    done = subprocess.run(["git", "status", "--porcelain"], cwd=root,
                          capture_output=True, text=True)
    return [line[3:].strip().split(" -> ")[-1] for line in done.stdout.splitlines() if line[3:]]


def flows(paths: list[str], root: Path = ROOT) -> list[str]:
    """Что течёт через тронутый рубеж — ЗНАНИЕ судьи, а не его вердикт.

    Правка рубежа нарушением не является; молчание о ней является: правящий не узнаёт, что через
    место течёт значение до клиента и чем это видно.
    """
    return _routes.lines(paths, root=root)


def stamp(сторож: str, нарушений: int, потоки: list[str], команда: str,
          root: Path = ROOT, точный: bool = True, детали: dict | None = None) -> str:
    """Подпись вердикта в общий журнал. Роль выводится из ЧИСЛА находок, а не из слов сторожа.

    `точный=False` означает, что судья держит только код возврата и числа находок у него нет:
    журнал говорит об этом прямо, иначе «1» читалось бы как «одно нарушение», хотя их было три.
    """
    роль = "ОТКАЗ" if нарушений else "ВЕРДИКТ"
    итог = (f"{нарушений} нарушений" if точный else "красный") if нарушений else "чисто"
    _, подпись = _stamp.sign("гейт", роль, f"{сторож}: {итог}", intent=сторож,
                             expected="прогон зелёный", actual=итог, cmd=команда,
                             detail={"сторож": сторож, "нарушений": нарушений, "потоки": потоки,
                                     "счёт": "точный" if точный else "по коду возврата",
                                     **(детали or {})},
                             root=root)
    return подпись


def close(сторож: str, нарушений: int, команда: str, root: Path = ROOT,
          точный: bool = True, детали: dict | None = None) -> int:
    """Хвост суда, общий у всех судей: задетые потоки вслух + подпись, вердикт кодом возврата."""
    потоки = flows(touched(root), root=root)
    print(f"── задетые потоки данных: {len(потоки) or 'нет'}")
    for строка in потоки:
        print(f"   ⇢ {строка}")
    print(stamp(сторож, нарушений, потоки, команда, root=root, точный=точный,
                детали=детали))
    return 1 if нарушений else 0
