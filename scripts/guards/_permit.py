#!/usr/bin/env python3
"""scripts/guards/_permit.py — снять запрет сторожа остатков может только человек.

Сторож печатал в каждом отказе, чем его выключить, и свежая консоль под давлением шла именно
туда. Здесь он держит ПАМЯТЬ о незакрытом: снятый запрет теряет не проверку, а хвост.

Переменная среды выключателем быть перестала. Запрет снимает РАЗРЕШЕНИЕ, чей ключ лежит в общем
журнале подписей, и появляется оно после «да» человека: команду запроса выносит вопросом хук
`vpm-permit.py`. Живёт 30 минут — забытое «снял и ушёл» истекает само.

Предел объявлен: файл разрешения на диске, и рука с Bash может написать его вместе с записью в
журнале. Дверь закрыта не от умысла, а от лёгкого пути под давлением; подделка остаётся
подписанной ложью в общем журнале — датированной и счётной.

Остальные четыре сторожа живут прежним рубильником (владелец 2026-09-05).
"""

from __future__ import annotations

import argparse
import json
import re
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import _stamp  # noqa: E402 — дорога к соседям кладётся строкой выше

СРОК = 30 * 60
СТОРОЖА = {"VPM_INTENT_GUARD": "сторож остатков"}
ЗАПРОС = re.compile(r"permit\.py\b[^\n|;]*--запрос\s+(VPM_[A-Z_]+)")
# Присваивание среды в любой форме: `VPM_X=off cmd`, `export VPM_X=off`, `env VPM_X=0 …`.
САМОВОЛКА = re.compile(r"\b(VPM_[A-Z_]+)\s*=\s*['\"]?(?:off|0|false)\b", re.I)
# Тело here-document и текст в кавычках — ДАННЫЕ, а не команда. Поймано на первом же прогоне:
# дверь запретила скрипт, который лишь ПЕРЕПИСЫВАЛ строку про выключатель (тот же класс, что
# ложная тревога гейта фактов). Сторож, обвиняющий рассказ о команде, врёт — и его выключают.
ТЕЛО = re.compile(r"<<-?\s*(['\"]?)(\w+)\1\r?\n.*?\r?\n\2\b", re.S)
В_КАВЫЧКАХ = re.compile(r"'[^']*'|\"[^\"]*\"")


def голая(команда: str) -> str:
    """Команда без данных: тело here-document и кавычки вырезаны."""
    return В_КАВЫЧКАХ.sub(" ", ТЕЛО.sub(" ", команда))


def запрос(команда: str) -> str | None:
    """Команда просит снять запрет — вернуть имя сторожа."""
    найдено = ЗАПРОС.search(голая(команда))
    return найдено.group(1) if найдено and найдено.group(1) in СТОРОЖА else None


def самоволка(команда: str) -> str | None:
    """Команда снимает запрет своей рукой — вернуть имя сторожа."""
    найдено = САМОВОЛКА.search(голая(команда))
    return найдено.group(1) if найдено and найдено.group(1) in СТОРОЖА else None


def команда(переменная: str, почему: str = "зачем именно снимаем") -> str:
    return f'.venv/bin/python scripts/guards/_permit.py --запрос {переменная} --почему "{почему}"'


def дом() -> Path:
    """Разрешения лежат в состоянии сессий, а не в дереве: это событие дня, а не факт репозитория."""
    return Path.home() / ".claude" / "state" / "vpm-permit"


def файл(переменная: str) -> Path:
    return дом() / f"{переменная}.json"


def снят(переменная: str, root: Path | None = None) -> bool:
    """Блок снят: живое разрешение, чей ключ подписи есть в общем журнале.

    Ключ проверяется обязательно: файл без записи в журнале — разрешение, которого никто не давал.
    """
    try:
        запись = json.loads(файл(переменная).read_text(encoding="utf-8"))
    except Exception:                          # noqa: BLE001 — нет файла или он битый = блок стоит
        return False
    if time.time() > float(запись.get("истекает") or 0):
        return False
    return bool(_stamp.find(str(запись.get("ключ") or ""), root or _stamp.ROOT))


def текст(переменная: str) -> str:
    """Строка, стоящая в отказах ВМЕСТО выключателя: не «выключи», а «попроси человека»."""
    return ("Снять запрет своей рукой нельзя. Попроси разрешение — в консоли появится «да/нет»:\n"
            f"    {команда(переменная)}\n"
            "Переменная среды сама по себе больше ничего не значит: решает человек, не сторож.")


def выдать(переменная: str, почему: str, root: Path | None = None) -> str:
    """Записать разрешение. Сюда попадают только после «да» человека — до запуска спросил хук."""
    if переменная not in СТОРОЖА:
        raise ValueError(f"сторож `{переменная}` не объявлен; известны {list(СТОРОЖА)}")
    if len(почему.strip()) < 12:
        raise ValueError("причина короче двенадцати знаков — человеку нечего решать")
    истекает = time.time() + СРОК
    ключ, подпись = _stamp.sign(
        "проба", "УЛИКА", f"человек снял блок: {СТОРОЖА[переменная]}",
        intent="разрешение снять блок", expected=f"{СТОРОЖА[переменная]} стоит",
        actual=f"снят на {СРОК // 60} мин",
        cmd=".venv/bin/python scripts/guards/_permit.py --список",
        detail={"сторож": переменная, "почему": почему, "истекает": истекает},
        root=root or _stamp.ROOT)
    дом().mkdir(parents=True, exist_ok=True)
    файл(переменная).write_text(json.dumps(
        {"сторож": переменная, "почему": почему, "выдан": time.time(), "истекает": истекает,
         "ключ": ключ}, ensure_ascii=False), encoding="utf-8")
    return подпись


def живые() -> list[dict]:
    записи = []
    for p in sorted(дом().glob("VPM_*.json")) if дом().is_dir() else []:
        try:
            запись = json.loads(p.read_text(encoding="utf-8"))
        except Exception:                      # noqa: BLE001 — битый файл разрешением не считается
            continue
        if time.time() <= float(запись.get("истекает") or 0):
            записи.append(запись)
    return записи


def main() -> int:
    ap = argparse.ArgumentParser(description="разрешение снять блок сторожа — решает человек")
    ap.add_argument("--запрос", metavar="VPM_X", help="попросить снятие (спросит человека да/нет)")
    ap.add_argument("--почему", default="", help="зачем снимаем — человек решает по этой строке")
    ap.add_argument("--список", action="store_true", help="живые разрешения")
    ap.add_argument("--отозвать", metavar="VPM_X", help="вернуть запрет на место немедленно")
    a = ap.parse_args()

    if a.отозвать:
        файл(a.отозвать).unlink(missing_ok=True)
        print(f"запрет возвращён: {СТОРОЖА.get(a.отозвать, a.отозвать)}")
        return 0
    if a.список:
        for з in живые():
            осталось = int((float(з["истекает"]) - time.time()) // 60)
            print(f"{з['сторож']}: снят ещё {осталось} мин · {з['почему']} · ⟦vpm {з['ключ']}⟧")
        if not живые():
            print("живых разрешений нет — сторожа на местах")
        return 0
    if a.запрос:
        print(выдать(a.запрос, a.почему))
        print(f"Запрет снят на {СРОК // 60} минут. Вернуть раньше: "
              f".venv/bin/python scripts/guards/_permit.py --отозвать {a.запрос}")
        return 0
    ap.print_help()
    return 2


if __name__ == "__main__":
    sys.exit(main())
