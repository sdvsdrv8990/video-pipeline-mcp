#!/usr/bin/env python3
"""scripts/guards/_stamp.py — подпись вывода: чем он был и по какому запросу.

Не сторож: ничего не судит и exit-кода не даёт. Отвечает на вопрос, которого сам вывод не несёт, —
УЛИКА это, ОТКАЗ или ВЕРДИКТ, каким было объявленное ожидание и где лежит полная запись.
Скопированная в другую сессию строка без подписи требует повторного дознания; с ключом хватает
одной команды: `reproduce.py --stamp <ключ>`.

Словари родов и ролей объявлены здесь и проверяются: незнакомое имя — отказ, а не тихая запись
неизвестно чего. Журнал свой (`stamps-*.jsonl`): производитель сценариев читает `trail-*` и
`scenarios-*`, и подмешивать в его вход другую форму записи нельзя.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
JOURNAL = ("tests", ".journal")
# Реестр находок — ХОЗЯИН состояния находки, показ остатков — производная от него: поэтому
# перечёркнутая находка гасит свой остаток, хотя закрывает хвост обычно подпись с его ключом.
НАХОДКИ = ("docs", "roadmap", "02_findings.md")
ПЕРЕЧЁРКНУТА = re.compile(r"~~(F\d+)~~")
# Находка гасит хвост, только когда она его ПРЕДМЕТ: такой хвост ОТКРЫВАЕТСЯ её ключом. Разбор по
# любому вхождению гасил бы и запись ПРО чужие находки — она перечисляет их в середине фразы.
ПРЕДМЕТ_НАХОДКА = re.compile(r"^\s*(F\d+)\b")
ФИНДИНГ = re.compile(r"\bF\d+\b")
# Дом остатков — под git, рядом со сторожем, который их читает. След дня объявлен рантаймом
# и игнорируется, поэтому остаток, живший только там, не переживал `git clean` и клон.
TAILS = ("scripts", "guards", "tails.jsonl")
ДОМ_ЧТЕНИЕ, ДОМ_ЗАПИСЬ = "tails.jsonl:чтение", "tails.jsonl:запись"


def _след(что: str) -> None:
    """Отметка обращения к дому остатков. Дом без следа неотличим от заброшенного: молчание значит
    и «никто не писал», и «никто не смотрел», а это разные беды."""
    try:
        sys.path.insert(0, str(ROOT / ".claude" / "hooks"))
        import _trace
        _trace.mark(что)
    except Exception:                          # noqa: BLE001 — след не важнее самой записи
        pass
ROLES = ("УЛИКА", "ОТКАЗ", "ВЕРДИКТ", "ОСТАТОК", "ОТЛОЖЕН", "В РАБОТЕ", "РЕШЕНИЕ",
         "ЗАМЫСЕЛ")
# `РЕШЕНИЕ` — выбор на РАЗВИЛКЕ, а не итог прогона: тем и отличается от `ВЕРДИКТ`.
# Не в `ПРИЗНАНИЯХ` намеренно: решением развилку ЗАКРЫВАЮТ, а не отодвигают.
# Членство здесь отнимает право ЗАКРЫВАТЬ хвост, а не меняет показ: признание — не итог.
ПРИЗНАНИЯ = ("ОТЛОЖЕН", "В РАБОТЕ")
KINDS = ("цикл", "гейт", "проба")
# Список исполнимых слов ПОИМЁННЫЙ, а не эвристика: «первое слово без пробелов» пропускает прозу
# («замер разделов памяти по regex» тоже начинается одним словом), и правило стало бы вакуумным.
RUNNERS = ("python", "python3", ".venv/bin/python", ".venv/bin/", "bash", "sh", "pytest", "ruff",
           "mypy", "bandit", "git", "grep", "sed", "awk", "ls", "find", "curl", "make", "npm",
           "node", "docker", "cat", "wc", "diff", "PYTHONPATH=", "VPM_")


def runnable(cmd: str) -> bool:
    """Строка похожа на команду: начинается исполнимым словом ЛИБО присваиванием среды.

    Судится ФОРМА, а не исполнимость: проверять запуском значит исполнять произвольную строку при
    подписи. Поэтому синтаксически битая команда правило проходит — и это ловится первым же
    повтором, а не молчанием.

    Присваивание (`PYTHONPATH=`, `VPM_`) исполнимым словом не является, но команда с него
    начинается законно — без этой половины законный повтор был бы отвергнут.
    """
    голова = cmd.strip()
    return bool(голова) and голова.startswith(RUNNERS)


def _head(root: Path) -> tuple[str, bool]:
    """Коммит и грязь дерева. Нет git — «улики нет», а не выдуманный ноль."""
    try:
        sha = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=str(root),
                             capture_output=True, text=True, timeout=20)
        dirty = subprocess.run(["git", "status", "--porcelain"], cwd=str(root),
                               capture_output=True, text=True, timeout=20)
    except (OSError, subprocess.SubprocessError):
        return "", False
    if sha.returncode != 0:
        return "", False
    return sha.stdout.strip(), bool(dirty.stdout.strip())


def зона_чиста(root: Path = ROOT) -> bool:
    """Правлено ли уже хоть одно СУДИМОЕ дерево. Правка доков и журнала чистоты не отменяет:
    предсказывать мешает написанный КОД, а не запись о нём."""
    import _evidence
    деревья = _evidence.деревья()
    корни = [к for д in деревья.values() if д.get("замысел") for к in д.get("корни") or []]
    if not корни:
        return True
    try:
        вывод = subprocess.run(["git", "diff", "--name-only", "HEAD", "--", *корни],
                               cwd=str(root), capture_output=True, text=True, timeout=20)
    except (OSError, subprocess.SubprocessError):
        return True                       # улики нет — не обвиняем
    # Дом остатков лежит В судимом дереве, но он журнал, а не код: без этой строки сама
    # дисциплина отравляла следующий замысел — записал остаток, и зона грязная, хотя не
    # написано ни строчки кода.
    дом = "/".join(TAILS)
    return not [п for п in вывод.stdout.split() if п != дом]


def sign(kind: str, role: str, what: str, *, intent: str = "", expected: str = "",
         actual: str = "", cmd: str = "", detail: dict | None = None, closes: str = "",
         кто: str = "владелец", зона: str = "", root: Path = ROOT) -> tuple[str, str]:
    """Записать наблюдение и вернуть (ключ, две строки подписи)."""
    if kind not in KINDS:
        raise ValueError(f"род `{kind}` не объявлен; известны {list(KINDS)}")
    if role not in ROLES:
        raise ValueError(f"роль `{role}` не объявлена; известны {list(ROLES)}")
    if зона:
        import _evidence
        известные = list(_evidence.зоны())
        if зона not in известные:
            raise ValueError(f"зона `{зона}` не объявлена; известны {известные}. Зона — словарь "
                             f"из `evidence.yaml`, а не свободный текст: иначе тем станет столько "
                             f"же, сколько записей, и группировать будет нечего.")
    # У решения обязателен ПРОГНОЗ: без него запись нечем проверить завтра, и журнал решений
    # перестаёт быть тем, на чём можно учиться, — становится прозой с ключом.
    if role == "РЕШЕНИЕ" and not expected.strip():
        raise ValueError(
            "решение без прогноза: назови `--expected` — к чему это приведёт и по какому "
            "признаку это будет видно. Решение, которое нельзя проверить постфактум, "
            "не отличается от мнения.")
    # Остаток судится тем же правилом: «чем продолжить» без команды — это пожелание, а не хвост.
    if role in ("УЛИКА", "ОСТАТОК") and not runnable(cmd):
        чем = "улика без команды повтора" if role == "УЛИКА" else "остаток без команды продолжения"
        raise ValueError(
            f"{чем}: `повторить` = {cmd!r}. То, что нельзя запустить, поднимать нечем — оно "
            f"стареет молча, как любая проза. Дай команду, начинающуюся с одного из "
            f"{list(RUNNERS[:6])}…")
    # Замысел объявляется ДО работы, и это проверяется, а не заявляется: если судимая зона уже
    # правлена, предсказывать нечего — код написан, и «ожидание» станет пересказом сделанного.
    # Ровно так подавляющее большинство прежних ожиданий стало пересказом сделанного.
    if role == "ЗАМЫСЕЛ":
        if not expected.strip():
            raise ValueError(
                "замысел без предсказания: назови `--expected` — какая СУЩЕСТВУЮЩАЯ проверка "
                "сменит цвет и почему. Замысел без этого не отличается от пересказа плана.")
        detail = {**(detail or {}), "зона-чиста": зона_чиста(root)}
    stamped = time.time()
    key = hashlib.sha1(f"{stamped}|{kind}|{what}".encode()).hexdigest()[:4]
    head, dirty = _head(root)
    day = time.strftime("%Y%m%d", time.localtime(stamped))
    path = root.joinpath(*JOURNAL) / f"stamps-{day}.jsonl"
    path.parent.mkdir(parents=True, exist_ok=True)
    line = sum(1 for _ in path.open(encoding="utf-8")) + 1 if path.exists() else 1
    where = f"{'/'.join(JOURNAL)}/{path.name}:{line}"
    record = {"ts": stamped, "key": key, "kind": kind, "role": role, "what": what,
              "intent": intent, "expected": expected, "actual": actual, "cmd": cmd,
              "зона": зона,
              "head": head, "dirty": dirty, "where": where, "closes": closes,
              "detail": {**(detail or {}), **({"кто": кто} if role == "РЕШЕНИЕ" else {})}}
    with path.open("a", encoding="utf-8") as out:
        out.write(json.dumps(record, ensure_ascii=False) + "\n")
    if role == "ОСТАТОК" or closes:
        дом = root.joinpath(*TAILS)
        дом.parent.mkdir(parents=True, exist_ok=True)
        with дом.open("a", encoding="utf-8") as в_дом:
            в_дом.write(json.dumps(record, ensure_ascii=False) + "\n")
        _след(ДОМ_ЗАПИСЬ)
    keys = [f"род={kind}"]
    if зона:
        keys.append(f"зона={зона}")
    if closes:
        keys.append(f"закрывает={closes}")
    if intent:
        keys.append(f"намерение={intent}")
    if expected:
        keys.append(f"ждали={expected}")
    if actual:
        keys.append(f"факт={actual}")
    keys += [f"HEAD={head or 'нет git'}{' (дерево грязное)' if dirty else ''}", f"запись={where}"]
    return key, f"⟦vpm {key} {role}⟧ {what}\n⟦ключи⟧ " + " · ".join(keys)


def мера_потолка(текст: str) -> str:
    """Потолок бывает числом, а бывает списком имён (слепая зона). Сравнивают и печатают МЕРУ:
    иначе отчёт вываливает весь список, а подпись со счётом не находит себя в содержимом."""
    строки = [s for s in текст.splitlines() if s.strip()]
    if len(строки) == 1 and строки[0].strip().isdigit():
        return строки[0].strip()
    return str(len(строки))


def сдвиг_потолка(сдвинутые: list[tuple[str, int, int, str]], причина: str,
                  root: Path = ROOT) -> int:
    """Сдвиг потолка уходит в журнал: вниз — вердиктом, ВВЕРХ — остатком.

    Вверх это не запись, а обещание: долг вырос, и до его закрытия остаток будет показываться
    на старте каждой сессии. Иначе «поднял потолок» стоит ровно одну строку в диффе и забывается.
    Механизм общий для ВСЕХ потолков: у каждого сторожа своя память о сдвиге давала разные
    ответы на один вопрос, а совет одного вёл в флаг, которого у другого нет.
    """
    if not сдвинутые:
        print("потолки не сдвинулись — записывать нечего")
        return 0
    for ось, было, стало, файл in сдвинутые:
        вверх = стало > было
        _, подпись = sign(
            "проба", "ОСТАТОК" if вверх else "ВЕРДИКТ",
            f"потолок «{ось}»: {было} → {стало} ({'ДОЛГ ВЫРОС' if вверх else 'долг закрыт вниз'}) — {причина}",
            intent="сдвиг потолка", expected=f"{было}", actual=f"{стало}",
            cmd=(f".venv/bin/python scripts/guards/invariants.py --check 2>&1 | grep '{ось}'"
                 if вверх else ""),
            detail={"ось": ось, "было": было, "стало": стало, "файл": файл, "причина": причина},
            # Потолок — всегда предмет СТОРОЖЕЙ, и зона у него объявляется, а не выводится из
            # пути команды: команда сдвига общая (`invariants.py --check`), и вывод по ней
            # называл бы зону догадкой — ровно то, что запрещает соседняя ось.
            зона="сторожа", root=root)
        print(подпись)
    return 0


def почему(argv: list[str]) -> str:
    """Причина сдвига потолка. Спрашивается у ЛЮБОГО сторожа: число, изменившееся без
    объяснения, через месяц неотличимо от опечатки, и «долг вырос» читается как «так и было»."""
    return argv[argv.index("--почему") + 1] if "--почему" in argv \
        and len(argv) > argv.index("--почему") + 1 else ""


def зона_записи(запись: dict) -> tuple[str, bool]:
    """Зона записи и объявлена ли она. Не объявлена — выводим из ПУТЕЙ команды продолжения:
    команда — улика, текст записи ею не является, поэтому по словам не гадаем.

    Нет словаря зон — зоны нет, но показ и ЗАПРЕТ остаются: хвост блокирует запись независимо от
    того, знаем ли мы его тему. Иначе снесённое объявление тихо отпирало бы дверь.
    """
    названа = str(запись.get("зона") or "")
    if названа:
        return названа, True
    try:
        import _evidence
    except ImportError:
        return "", False
    return _evidence.зона_команды(str(запись.get("cmd") or "")), False


def тип_остатка(запись: dict) -> str:
    """Род хвоста выводится из самой записи, а не из отдельного поля: поле пришлось бы заполнять
    руками, и оно повторило бы судьбу `intent` — заполнено у 10 из 25."""
    detail = запись.get("detail") or {}
    if "было" in detail and "стало" in detail:
        return "долг"
    if ФИНДИНГ.search(str(запись.get("what") or "")):
        return "находка"
    return "работа"


def перечёркнутые(root: Path = ROOT) -> set[str]:
    """Находки, закрытые в реестре. Реестра нет — пусто, а не «все закрыты»: отсутствие улики
    не гасит ни одного хвоста."""
    путь = root.joinpath(*НАХОДКИ)
    if not путь.exists():
        return set()
    return set(ПЕРЕЧЁРКНУТА.findall(путь.read_text(encoding="utf-8", errors="replace")))


def детали_сдвига(detail: dict) -> bool:
    """Запись — это сдвиг потолка ВВЕРХ."""
    было, стало = detail.get("было"), detail.get("стало")
    return isinstance(было, int) and isinstance(стало, int) and стало > было


def гасит_реестр(запись: dict, зачёркнуты: set[str]) -> bool:
    """Хвост закрыт РЕЕСТРОМ: его предмет — находка, и она перечёркнута."""
    предмет = ПРЕДМЕТ_НАХОДКА.match(str(запись.get("what") or ""))
    return предмет is not None and предмет.group(1) in зачёркнуты


def _рост_долга(хвост: dict, все: list[dict]) -> int:
    """Сколько раз потолок в ЭТОЙ зоне поднимали уже ПОСЛЕ того, как хвост записан.

    Растущий долг рядом — довод закрыть хвост раньше: место, где потолки едут вверх, дешевеет
    от работы больше прочих. Считаются только сдвиги позже хвоста: прежние он уже пережил.
    """
    зона, _ = зона_записи(хвост)
    if not зона:
        return 0
    рост = 0
    for другой in все:
        detail = другой.get("detail") or {}
        if детали_сдвига(detail) and другой.get("ts", 0) > хвост.get("ts", 0):
            чужая, _ = зона_записи(другой)
            рост += чужая == зона
    return рост


def _на_пути(хвост: dict, все: list[dict]) -> bool:
    """Взятая работа называет этот ключ — значит хвост стоит у неё на пути.

    Улика — ключ в тексте взятого хвоста: так доска и пишет («поглощает `bcfd`»). Ни один взятый
    хвост никого не называет — множитель у всех единица, и порядок остаётся возрастом.
    """
    ключ = хвост.get("key") or ""
    for другой in все:
        if not другой.get("в работе") or другой is хвост:
            continue
        if ключ and ключ in f"{другой.get('what', '')} {другой.get('expected', '')}":
            return True
    return False


def приоритет(хвост: dict, все: list[dict], сейчас: float | None = None) -> float:
    """Правило владельца: возраст × рост долга × стоит ли на пути у взятого.

    Множители, а не сумма: слагаемые пришлось бы взвешивать в одних единицах, а это разные вещи —
    время, растущий долг и блокировка чужой работы. Нейтральный множитель — единица, поэтому
    хвост без растущего долга и вне чужого пути ранжируется чистым возрастом, как и раньше.
    """
    сейчас = time.time() if сейчас is None else сейчас
    возраст = max(0.0, (сейчас - float(хвост.get("ts") or 0)) / 86400)
    return возраст * (1 + _рост_долга(хвост, все)) * (2.0 if _на_пути(хвост, все) else 1.0)


def tails(root: Path = ROOT) -> list[dict]:
    """Незакрытые остатки, старые сверху. Закрытие — ДРУГАЯ подпись, назвавшая ключ хвоста.

    Дом один и он в git (`TAILS`): хвост живёт до закрытия, а «неделю назад» — самый частый его
    возраст, поэтому день-журнала мало. Дома нет — пусто, а не выдуманный ноль.
    """
    записи, закрыты, отложены, в_работе = [], set(), set(), set()
    дом = root.joinpath(*TAILS)
    if дом.exists():
        _след(ДОМ_ЧТЕНИЕ)
        for row in дом.read_text(encoding="utf-8", errors="replace").splitlines():
            if not row.strip():
                continue
            try:
                запись = json.loads(row)
            except json.JSONDecodeError:
                continue
            # Закрывает ТОЛЬКО не-признание: иначе «отложил» и «беру» тихо равнялись бы «закрыл»,
            # и хвост исчезал бы из показа вместе с запретом — та потеря, ради которой всё затевалось.
            if запись.get("closes") and запись.get("role") not in ПРИЗНАНИЯ:
                закрыты.add(запись["closes"])
            # Отложенный хвост из показа НЕ уходит: он не закрыт. Уходит он только из блокировки —
            # иначе «отложил» стало бы способом забыть, а не решением подождать.
            if запись.get("role") == "ОТЛОЖЕН" and запись.get("closes"):
                отложены.add(запись["closes"])
            # «В работе» отличается от «отложен» смыслом, а не действием: запрет снимают оба, но
            # показ должен различать взятое сегодня и отодвинутое — иначе брошенное не видно.
            if запись.get("role") == "В РАБОТЕ" and запись.get("closes"):
                в_работе.add(запись["closes"])
            if запись.get("role") == "ОСТАТОК":
                записи.append(запись)
    зачёркнуты = перечёркнутые(root)
    живые = [z for z in sorted(записи, key=lambda z: z.get("ts", 0))
             if z["key"] not in закрыты and not гасит_реестр(z, зачёркнуты)]
    for хвост in живые:
        хвост["отложен"] = хвост["key"] in отложены
        хвост["в работе"] = хвост["key"] in в_работе
        хвост["признан"] = хвост["отложен"] or хвост["в работе"]
        хвост["зона"], хвост["зона названа"] = зона_записи(хвост)
        хвост["тип"] = тип_остатка(хвост)
    for хвост in живые:
        хвост["приоритет"] = приоритет(хвост, живые)
    return живые


def погашены_реестром(root: Path = ROOT) -> list[dict]:
    """Хвосты, которые гасит реестр, а не подпись. Печатаются отдельной строкой: молча исчезнувший
    хвост неотличим от потерянного, а закрытие чужой рукой обязано быть видно."""
    зачёркнуты = перечёркнутые(root)
    дом = root.joinpath(*TAILS)
    if not дом.exists() or not зачёркнуты:
        return []
    _след(ДОМ_ЧТЕНИЕ)
    закрыты = set()
    хвосты = []
    for row in дом.read_text(encoding="utf-8", errors="replace").splitlines():
        if not row.strip():
            continue
        try:
            запись = json.loads(row)
        except json.JSONDecodeError:
            continue
        if запись.get("closes") and запись.get("role") not in ПРИЗНАНИЯ:
            закрыты.add(запись["closes"])
        if запись.get("role") == "ОСТАТОК" and гасит_реестр(запись, зачёркнуты):
            хвосты.append(запись)
    return [x for x in хвосты if x["key"] not in закрыты]


ИСХОДЫ = ("сработал", "молчал")
# Поля условия закрыты списком: условие — НАБОР, а не слово. Свободная проза здесь означала бы,
# что причину исхода нельзя сопоставить между прогонами, и эксперимент «сменили порядок шагов»
# стал бы рассказом. `сошлось` считается, а не объявляется: иначе автор записи судит сам себя.
ПОЛЯ_УСЛОВИЯ = ("имя", "ждали", "факт")


def условие(имя: str, ждали: object, факт: object, *, решает: bool = True) -> dict:
    """Одно условие шага: имя, ожидание, факт, ВЫВЕДЕННОЕ совпадение и право решать исход.

    Условие — часть логики, способная сменить исход, поэтому у него обязательны все три поля: по
    одному имени нельзя ни повторить проверку, ни сравнить два прогона.

    `решает=False` — условие остаётся в наборе картиной, но исхода не гасит. Без этого различия
    набор АЛЬТЕРНАТИВ («сгодится любой из трёх признаков») судился бы правилом «сошлись все», и
    такой шаг молчал бы ВСЕГДА: поймано первым же прогоном росписи на самой росписи (`a244`).
    """
    if not имя.strip():
        raise ValueError("условие без имени: сопоставить его между прогонами будет нечем")
    return {"имя": имя, "ждали": ждали, "факт": факт, "сошлось": ждали == факт, "решает": решает}


ПОЛЯ_ШАГА = ("имя", "механизм", "условия", "исход", "причина", "следствие")


def строка_шага(имя: str, механизм: str, условия: list[dict], *, исход: str, следствие: str,
                прогон: str = "", предыдущий: str = "") -> dict:
    """Один ряд росписи: условия набором, исход, ВЫВЕДЕННАЯ причина и следствие.

    Молчание — полноправная запись, а не отсутствие её: шаг, не сработавший потому, что условие
    ложно, обязан назвать ЭТО условие. Иначе тишина неотличима от отсутствия механизма, и класс
    немого промаха воспроизводится в самой системе учёта.

    Причина не сочиняется словами, а выводится из набора: сработал — причина в том, что все
    условия сошлись; молчал — причина в поимённо названных разошедшихся. Поэтому «молчал при всех
    сошедшихся условиях» и «сработал при разошедшихся» — противоречия, и запись их не принимает:
    подпись, которой можно объяснить любой исход, ничего не судит.
    """
    if исход not in ИСХОДЫ:
        raise ValueError(f"исход `{исход}` не объявлен; известны {list(ИСХОДЫ)}")
    if not условия:
        raise ValueError("шаг без условий: судить можно было бы только срабатывание, а заказ — "
                         "судить условия срабатывания И молчания")
    for у in условия:
        нет = [поле for поле in ПОЛЯ_УСЛОВИЯ if поле not in у]
        if нет:
            raise ValueError(f"условие {у.get('имя', '?')!r} неполно: нет {нет}. Собирай его "
                             f"через `условие()`, а не словарём от руки")
    # Исход считается по РЕШАЮЩИМ условиям: остальные — картина набора, и гасить шаг не вправе.
    разошлись = [у["имя"] for у in условия if у.get("решает", True) and not у.get("сошлось")]
    if исход == "сработал" and разошлись:
        raise ValueError(f"шаг заявлен сработавшим при разошедшихся условиях {разошлись}: "
                         f"так объясняется любой исход, и запись перестаёт быть уликой")
    if исход == "молчал" and not разошлись:
        raise ValueError("шаг заявлен молчавшим, а все условия сошлись: назови условие, которое "
                         "его остановило, иначе молчание нечем отличить от отсутствия механизма")
    причина = ("все условия сошлись" if исход == "сработал"
               else "условия не сошлись: " + ", ".join(f"«{имя}»" for имя in разошлись))
    return {"имя": имя, "механизм": механизм, "условия": условия, "исход": исход,
            "причина": причина, "следствие": следствие,
            "прогон": прогон, "предыдущий": предыдущий}


def шаг(имя: str, механизм: str, условия: list[dict], *, исход: str, следствие: str,
        прогон: str = "", предыдущий: str = "", cmd: str = "",
        зона: str = "", root: Path = ROOT) -> tuple[str, str]:
    """Роспись ОДНОГО шага отдельной подписью — для механизма, у которого шаг редкий и важный."""
    if not cmd.strip():
        raise ValueError("шаг без команды поднятия: роспись, которую нечем поднять, — проза. "
                         "Назови `cmd` — чем вернуться к ЭТОМУ шагу")
    ряд = строка_шага(имя, механизм, условия, исход=исход, следствие=следствие,
                      прогон=прогон, предыдущий=предыдущий)
    return sign("проба", "УЛИКА", f"шаг «{имя}» {исход}: {следствие}",
                intent=f"роспись шага · {механизм}",
                expected=" · ".join(f"{у['имя']}={у['ждали']!r}" for у in условия),
                actual=ряд["причина"], cmd=cmd, detail={"шаг": ряд}, зона=зона, root=root)


def роспись(ряды: list[dict], *, механизм: str, cmd: str, зона: str = "",
            root: Path = ROOT) -> tuple[str, str]:
    """Роспись МНОГИХ шагов одного прогона ОДНОЙ подписью.

    Механизм, делающий полсотни шагов за прогон, отдельными подписями залил бы журнал, и его
    перестали бы читать — а нечитаемая улика равна её отсутствию. Ряды собирает `строка_шага`:
    словарь от руки прошёл бы мимо всех отказов, поэтому набор полей проверяется здесь.
    """
    if not cmd.strip():
        raise ValueError("роспись без команды поднятия: её нечем повторить")
    if not ряды:
        raise ValueError("роспись без шагов: молчание всего механизма — тоже утверждение, "
                         "но записывать его нечем, если ни один шаг не назван")
    for ряд in ряды:
        нет = [поле for поле in ПОЛЯ_ШАГА if поле not in ряд]
        if нет:
            raise ValueError(f"ряд {ряд.get('имя', '?')!r} неполон: нет {нет}. Собирай его "
                             f"через `строка_шага()` — она и выводит причину")
    сработали = [ряд["имя"] for ряд in ряды if ряд["исход"] == "сработал"]
    return sign("проба", "УЛИКА",
                f"роспись «{механизм}»: шагов {len(ряды)}, сработали {len(сработали)}, "
                f"молчали {len(ряды) - len(сработали)}",
                intent=f"роспись шага · {механизм}",
                expected=f"каждый шаг назван условиями: {len(ряды)}",
                actual="сработали: " + (", ".join(f"«{имя}»" for имя in сработали) or "ни один"),
                cmd=cmd, detail={"шаги": ряды}, зона=зона, root=root)


def шаги(прогон: str, root: Path = ROOT) -> list[dict]:
    """Роспись шагов ОДНОГО прогона в порядке записи. Пусто — росписи нет, а не «шагов нет»."""
    найдено = []
    for path in sorted(root.joinpath(*JOURNAL).glob("stamps-*.jsonl")):
        for row in path.read_text(encoding="utf-8", errors="replace").splitlines():
            if not row.strip():
                continue
            try:
                запись = json.loads(row)
            except json.JSONDecodeError:
                continue
            подробно = запись.get("detail") or {}
            # Две формы записи законны: отдельная подпись у редкого шага и ряд у механизма,
            # делающего их полсотни за прогон. Читатель один — иначе цена шага считалась бы
            # по половине росписи и молчала бы о второй.
            ряды = подробно.get("шаги") or ([подробно["шаг"]] if подробно.get("шаг") else [])
            for ш in ряды:
                if not прогон or ш.get("прогон") == прогон:
                    найдено.append({**ш, "ключ": запись.get("key"), "ts": запись.get("ts")})
    return sorted(найдено, key=lambda ш: ш.get("ts") or 0)


def молчавшие(root: Path = ROOT) -> list[tuple[str, int, int]]:
    """(шаг, сработал раз, молчал раз) по всей росписи — читатель цены шага.

    Шаг, который ни разу не сработал, — кандидат на снос: он стоит в цепочке и ни на что не
    повлиял. Это и есть вопрос владельца «какие инструкции реально полезны, а какие нет», только
    посчитанный, а не оценённый на глаз.
    """
    счёт: dict[str, list[int]] = {}
    for ш in шаги("", root):
        пара = счёт.setdefault(ш["имя"], [0, 0])
        пара[0 if ш.get("исход") == "сработал" else 1] += 1
    return sorted(((имя, п[0], п[1]) for имя, п in счёт.items()), key=lambda р: (р[1], -р[2]))


def find(key: str, root: Path = ROOT) -> list[dict]:
    """Записи по ключу. Ключ короткий, поэтому совпадений бывает несколько — отдаём все."""
    found = []
    for path in sorted(root.joinpath(*JOURNAL).glob("stamps-*.jsonl")):
        for row in path.read_text(encoding="utf-8", errors="replace").splitlines():
            if not row.strip():
                continue
            try:
                record = json.loads(row)
            except json.JSONDecodeError:
                continue                 # обрыв строки не отменяет остальных
            if record.get("key") == key:
                found.append(record)
    return found


def цена(root: Path = ROOT) -> dict[str, dict]:
    """Экономика цикла по журналу: за что заплачено и что за это поймано.

    Считается по НАМЕРЕНИЯМ, а не по прогонам: повтор после фикса — тот же вопрос, заданный
    второй раз, и считать его отдельным наблюдением значит завышать выигрыш втрое.
    """
    итог: dict[str, dict] = {}
    for path in sorted(root.joinpath(*JOURNAL).glob("stamps-*.jsonl")):
        for row in path.read_text(encoding="utf-8", errors="replace").splitlines():
            if not row.strip():
                continue
            try:
                запись = json.loads(row)
            except json.JSONDecodeError:
                continue
            if запись.get("kind") != "цикл" or запись.get("role") != "ВЕРДИКТ":
                continue
            имя = запись.get("intent") or "(без имени)"
            подробность = запись.get("detail") or {}
            место = итог.setdefault(имя, {"прогонов": 0, "поймал": 0, "секунд": 0.0,
                                          "без длительности": 0})
            место["прогонов"] += 1
            место["поймал"] += len(подробность.get("риск") or [])
            секунд = float(подробность.get("секунд") or 0)
            место["секунд"] += секунд
            место["без длительности"] += секунд == 0
    return итог


def трение(дом: Path | None = None) -> list[tuple[int, int, int]]:
    """Отказы гейта фактов по сессиям: (отказов, разных ключей, упёртых).

    Читателя у этого счёта не было вовсе, поэтому «сторож кричит» не отличалось от «сторож молчит».
    Отказов примерно поровну с ключами — это пошлина за широту работы, а не упрямство ИИ.
    """
    корень = дом or Path.home() / ".claude" / "state" / "vpm-fact-gate"
    ряд = []
    for путь in sorted(корень.glob("*.json")) if корень.is_dir() else []:
        try:
            с = json.loads(путь.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            continue
        ряд.append((int(с.get("denials") or 0), len(с.get("denied") or {}),
                    sum(1 for v in (с.get("denied_count") or {}).values() if v >= 3)))
    return sorted(ряд, reverse=True)


def печать_хвостов(хвосты: list[dict], погашенные: list[dict] | None = None) -> None:
    """Показ остатков: первой строкой — что закрывать ПЕРВЫМ, дальше группы зона × тип.

    До этого показ шёл возрастом и одним списком: старший хвост оказывался сверху, даже если
    он из зоны, которой сегодня не занимаются, и «что закрыть первым» приходилось решать чтением
    прозы. Зона, у которой нет объявления, названа выведенной вслух — иначе догадка неотличима
    от факта, а число невыведенных нечем опустить.
    """
    if not хвосты:
        print("незакрытых остатков нет")
    else:
        первый = max(хвосты, key=lambda x: x["приоритет"])
        печать_первого(первый)
        по_группам: dict[tuple[str, str], list[dict]] = {}
        for хвост in хвосты:
            по_группам.setdefault((хвост["зона"] or "не названа", хвост["тип"]), []).append(хвост)
        for (зона, тип), группа in sorted(по_группам.items(), key=_вес_группы):
            print(f"\n── зона `{зона}` · {тип} ({len(группа)})")
            for хвост in sorted(группа, key=lambda x: -x["приоритет"]):
                возраст = (time.time() - хвост.get("ts", 0)) / 86400
                метка = "" if хвост["зона названа"] else " · зона выведена"
                # Помечается НЕпризнанный: признаны почти все, и метка на них была бы шумом, а
                # запись блокируют как раз непризнанные.
                признан = "" if хвост.get("признан") else " · НЕ ПРИЗНАН, блокирует запись"
                print(f"⟦vpm {хвост['key']} ОСТАТОК⟧ {хвост['what']}  "
                      f"(дней: {возраст:.0f} · приоритет {хвост['приоритет']:.0f}{метка}{признан})")
                print(f"  ждали: {хвост.get('expected') or '—'}")
                print(f"  продолжить: {хвост.get('cmd') or '—'}")
        безымянных = sum(1 for x in хвосты if not x["зона названа"])
        print(f"\nвсего {len(хвосты)} · зона выведена у {безымянных}: у подписи есть `--зона`, "
              f"и объявленная зона точнее выведенной из команды")
    for хвост in погашенные or []:
        print(f"\n⟦vpm {хвост['key']}⟧ погашен РЕЕСТРОМ: находка перечёркнута в "
              f"{'/'.join(НАХОДКИ)}, а закрывающая подпись назвала другой ключ — "
              f"{хвост['what'][:110]}")


def печать_первого(хвост: dict) -> None:
    """Первая строка показа: правило, по которому выбран хвост, печатается вместе с ответом —
    иначе число «приоритет 12» неотличимо от мнения."""
    зона = хвост["зона"] or "не названа"
    выведена = "" if хвост["зона названа"] else " (выведена)"
    print(f"ПЕРВЫМ `{хвост['key']}` · зона {зона}{выведена} · {хвост['тип']} · "
          f"приоритет {хвост['приоритет']:.0f} = возраст(дней) × (1 + рост долга в зоне) × "
          f"(2, если стоит на пути у взятого)")
    print(f"  {хвост['what'][:150]}")
    print(f"  продолжить: {хвост.get('cmd') or '—'}")


def _вес_группы(пара: tuple[tuple[str, str], list[dict]]) -> tuple[float, str, str]:
    """Группы идут по САМОМУ срочному хвосту внутри, а не по алфавиту зоны: иначе зона, где горит,
    оказывается внизу из-за буквы."""
    (зона, тип), группа = пара
    return (-max(x["приоритет"] for x in группа), зона, тип)


def печать_цены(итог: dict[str, dict]) -> None:
    """Отчёт для человека: что заплачено, что поймано, чего замерить не удалось."""
    if not итог:
        print("вердиктов цикла в журнале нет — считать нечего")
        return
    поймавших = sum(1 for м in итог.values() if м["поймал"])
    прогонов = sum(м["прогонов"] for м in итог.values())
    секунд = sum(м["секунд"] for м in итог.values())
    немые = sum(м["без длительности"] for м in итог.values())
    print(f"намерений {len(итог)} · прогонов {прогонов} · "
          f"поймали незаявленное {поймавших} из {len(итог)}")
    print(f"замерено {секунд / 60:.0f} мин; прогонов без записанной длительности: {немые}\n")
    for имя, м in sorted(итог.items(), key=lambda x: -x[1]["поймал"]):
        метка = f"поймал {м['поймал']}" if м["поймал"] else "вхолостую"
        цена_ = f"{м['секунд'] / 60:.1f} мин" if м["секунд"] else "длительность не записана"
        print(f"  {имя:26} прогонов {м['прогонов']}  {метка:12} {цена_}")
    ряд = трение()
    if ряд:
        отказов = sum(о for о, _, _ in ряд)
        ключей = sum(к for _, к, _ in ряд)
        упёртых = sum(у for _, _, у in ряд)
        print(f"\nтрение гейта фактов: отказов {отказов} · разных файлов {ключей} · "
              f"упёртых {упёртых} (сессий с отказами: {sum(1 for о, _, _ in ряд if о)})")
        print("  отказов ≈ файлов — пошлина за широту работы; отказов заметно больше — правка "
              "идёт без взгляда")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    # `--tails` спрашивает журнал и ничего не подписывает, поэтому обязательные поля подписи для
    # него не обязательны: иначе прочитать остаток можно было бы только заведя новый.
