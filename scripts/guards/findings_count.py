"""scripts/guards/findings_count.py — судья реестра находок: строки обязаны разбираться.

Паспорт: будит редактирование, гейт CI · читает docs/roadmap/02_findings.md,
  scripts/guards/findings_count_baseline.txt · расписывает «поднять реестр → разобрать строки →
  сверить с полом» · подписывает через _verdict.
Зовёт: _stamp, _verdict.
Зовут: invariants, гейт CI и pre-commit.

Находки не удаляются, только закрываются, поэтому разобранных строк не может стать меньше;
уменьшение значит сломанный формат таблицы — а вместе с ним слепнет ось «статус мимо реестра»,
которая читает те же строки и на пустом наборе молча зеленеет.

Закрыта = идентификатор строки зачёркнут ИЛИ в колонке важности стоит знак закрытия. Проза ячейки
не разбирается: «ЗАКРЫТ (остаток)» встречается и у открытых находок. Разбор здесь ОДИН на весь
проект — второй читатель того же реестра дал бы второй вердикт.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import _stamp
import _verdict

REGISTRY = Path(__file__).resolve().parents[2] / "docs" / "roadmap" / "02_findings.md"
FLOOR = Path(__file__).with_name("findings_count_baseline.txt")
ROW = re.compile(r"^\| (~~)?\*{0,2}(F\d+)\*{0,2}(?:~~)?\s*\|([^|]*)\|")
CLOSED = ("✅", "🟢")


def scan(text: str) -> dict[str, bool]:
    """{идентификатор: закрыта}. Первая строка каноническая: ниже лежат таблицы переформулировок."""
    rows: dict[str, bool] = {}
    for line in text.splitlines():
        if m := ROW.match(line):
            closed = bool(m.group(1)) or any(mark in m.group(3) for mark in CLOSED)
            rows.setdefault(m.group(2), closed)
    return rows


class НетОбразца(RuntimeError):
    """Источник есть, но живой строки из него не поднять: судить форму нечем, и это отказ."""


# Идентификатор строки вместе с его оформлением: зачёркивание и жирность — часть формы, а не шум.
ROW_ID = re.compile(r"(?<=^\| )(?:~~)?\*{0,2}F\d+\*{0,2}(?:~~)?")


def образец(registry: Path | None = None) -> dict[str, str]:
    """Живые строки ИЗ реестра: шапка, разделитель, открытая находка и закрытая.

    Набор, сочинивший строку сам, судит форму, которой в источнике может уже не быть: сдвиг
    разметки на один пробел ослепил разбор большинства строк, а набор остался зелёным ⟦vpm ec31⟧.
    Образец переносит форму из источника в пробу целиком, поэтому смена формы доезжает до набора
    сама — без второго списка, который пришлось бы помнить.

    Нет источника или в нём нет обоих родов строк — отказ `НетОбразца`, а не пустой словарь:
    молча выданная пустота снова сделала бы пробу зелёной на любой форме.
    """
    дом = registry or REGISTRY
    if not дом.exists():
        raise НетОбразца(f"реестра нет — {дом}: форму брать неоткуда")
    открытая = закрытая = шапка = разделитель = ""
    прежняя = ""
    for строка in дом.read_text(encoding="utf-8").splitlines():
        # Шапку узнаём ПО РАЗДЕЛИТЕЛЮ, а не по первому слову: имена колонок — часть формы, и
        # правило «строка начинается с ID» было бы вторым знанием о ней, которое рассохнется.
        if not разделитель and строка.startswith("|---"):
            разделитель, шапка = строка, прежняя
        прежняя = строка
        if not (m := ROW.match(строка)):
            continue
        закрыта = bool(m.group(1)) or any(знак in m.group(3) for знак in CLOSED)
        if закрыта and not закрытая:
            закрытая = строка
        elif not закрыта and not открытая:
            открытая = строка
    нет = [имя for имя, знач in (("шапка", шапка), ("разделитель", разделитель),
                                 ("открытая", открытая), ("закрытая", закрытая)) if not знач]
    if нет:
        raise НетОбразца(f"в реестре {дом} не нашлось: {', '.join(нет)} — "
                         f"форма источника неполна, и судить по ней нельзя")
    return {"шапка": шапка, "разделитель": разделитель,
            "открытая": открытая, "закрытая": закрытая}


# Состояния ОДНОЙ строки источника: каждое имя описывает, чем строка отличается от живой. Проба
# называет состояние, а содержимое всегда берётся из реестра — документ не улика и копии в коде
# ему не нужны (правило владельца 2026-09-14).
СОСТОЯНИЯ = {
    "как-есть": lambda с: с,
    # Та же находка, упомянутая прозой: разметки таблицы нет, значит и строкой она не считается.
    "проза": lambda с: "Находка " + " ".join(с.strip("| ").split("|")[0].split()) + " упомянута прозой.",
    # Чужая серия: идентификатор из другой серии живёт в своих реестрах и нашим не считается.
    "чужая-серия": lambda с: ROW_ID.sub(lambda m: m.group(0).replace("F", "G"), с, count=1),
    # Зачёркивание снято: закрытость остаётся только за знаком в колонке важности.
    "без-зачёркивания": lambda с: ROW_ID.sub(lambda m: m.group(0).replace("~~", ""), с, count=1),
    # Знак закрытия убран из колонки важности: закрытой строка остаётся лишь зачёркнутой.
    "без-знака-закрытия": lambda с: _без_знаков(с),
    # Зачёркнута, но БЕЗ знака: закрытие держится только оформлением идентификатора.
    "зачёркнутая-без-знака": lambda с: ROW_ID.sub(
        lambda m: f"~~{m.group(0).replace('~~', '')}~~", _без_знаков(с), count=1),
    # Жирный идентификатор: оформление реестра, которое разбор обязан видеть насквозь.
    "жирный": lambda с: ROW_ID.sub(
        lambda m: f"**{m.group(0).replace('*', '')}**", с, count=1),
    # Знак закрытия берётся ИЗ ОБЪЯВЛЕНИЯ судьи, а не пишется здесь: список знаков один.
    "знак-закрытия": lambda с: со_знаком(с, CLOSED[-1]),
    # Переход: начальный знак берётся ИЗ САМОЙ строки, итоговый — из объявления судьи. Ни один
    # знак не пишется здесь: сменят палитру реестра — состояние поедет вместе с ней.
    "знак-перехода": lambda с: со_знаком(с, f"{знак_важности(с)}→{CLOSED[-1]}"),
}


def со_знаком(строка: str, знак: str) -> str:
    """Та же строка с заданным знаком в колонке важности: перебор знаков — дело пробы."""
    куски = _без_знаков(строка).split("|")
    if len(куски) > 2:
        куски[2] = f" {знак} "
    return "|".join(куски)


def знак_важности(строка: str) -> str:
    """Что стоит в колонке важности ЭТОЙ строки. Знаки живут в реестре, а не в нашем коде."""
    куски = строка.split("|")
    return куски[2].strip() if len(куски) > 2 else ""


def _без_знаков(строка: str) -> str:
    """Колонка важности без знаков закрытия: остальные колонки не трогаем — там живёт проза.

    Опустевшая колонка не заполняется своим знаком: «нет знака закрытия» — и есть состояние
    открытой, а подставленный нами символ был бы вторым знанием о палитре реестра.
    """
    куски = строка.split("|")
    if len(куски) > 2:
        for знак in CLOSED:
            куски[2] = куски[2].replace(знак, "")
        куски[2] = f" {куски[2].strip()} "
    return "|".join(куски)


def состояние(строка: str, имя: str) -> str:
    """Живая строка источника в объявленном состоянии. Неизвестное имя — отказ, а не тихий возврат."""
    if имя not in СОСТОЯНИЯ:
        raise НетОбразца(f"состояния `{имя}` нет; объявлены {sorted(СОСТОЯНИЯ)}")
    return СОСТОЯНИЯ[имя](строка)


def разбирает(строка: str) -> bool:
    """Признаёт ли судья эту строку строкой СВОЕГО источника. Договор для оси «копия формы»:
    по нему она отличает копию реестра в наборе от любой другой строки."""
    return bool(ROW.match(строка.strip()))


def по_образцу(строка: str, ident: str) -> str:
    """Та же строка источника под другим идентификатором: СКОЛЬКО строк, решает проба; КАК они
    выглядят — источник. Оформление передаётся вместе с именем: зачёркнутый идентификатор означает
    закрытую находку, голый — открытую."""
    новая, сколько = ROW_ID.subn(ident, строка, count=1)
    if not сколько:
        raise НетОбразца(f"в образце не нашёлся идентификатор: {строка[:60]}")
    return новая


def _named_tree(argv: list[str]) -> Path | None:
    """`--root <путь>` — судить НАЗВАННОЕ дерево, а не то, в котором лежит сам сторож.

    Без флага вердикт достижим только из python-кода: объявление умеет запустить команду, но не
    умеет передать ей корень, и обе стороны сторожа остаются недостижимы из карты.
    """
    for i, arg in enumerate(argv):
        if arg == "--root" and i + 1 < len(argv):
            return Path(argv[i + 1]).resolve()
        if arg.startswith("--root="):
            return Path(arg.split("=", 1)[1]).resolve()
    return None


ПОВТОР = ".venv/bin/python scripts/guards/findings_count.py --check"


def _итог(ряды: list[dict], код: int, чужое: bool) -> int:
    """Записать роспись и вернуть код. Чужое дерево не расписываем — судим его не нашей меркой.

    Роспись живёт в НАШЕМ журнале, и ряд о чужом дереве читался бы как шаг по своему: та же
    причина, по которой туда не уходит подпись вердикта.
    """
    if not чужое:
        _stamp.роспись(ряды, механизм="findings_count.py", cmd=ПОВТОР, зона="сторожа")
    return код


def main() -> int:
    try:                                       # след: без отметки механизм выглядит пылящимся
        sys.path.insert(0, str(Path(__file__).resolve().parents[2] / ".claude" / "hooks"))
        import _trace
        _trace.mark("findings_count.py")
    except Exception:  # след не важнее самой работы
        pass
    global REGISTRY, FLOOR
    if (named := _named_tree(sys.argv)) is not None:
        REGISTRY = named / "docs" / "roadmap" / "02_findings.md"
        FLOOR = named / "scripts" / "guards" / "findings_count_baseline.txt"
    чужое = named is not None
    ряды = [_stamp.строка_шага(
        "поднять реестр", "REGISTRY.exists",
        [_stamp.условие("реестр находок лежит на месте", True, REGISTRY.exists())],
        исход="сработал" if REGISTRY.exists() else "молчал",
        следствие=f"источник читается: {REGISTRY.name}" if REGISTRY.exists()
        else "реестра нет — судить нечем, и ноль строк тут не чистота")]
    if not REGISTRY.exists():
        print(f"findings_count: реестра нет — {REGISTRY}", file=sys.stderr)
        return _итог(ряды, 2, чужое)
    text = REGISTRY.read_text(encoding="utf-8")
    rows = scan(text)
    ряды.append(_stamp.строка_шага(
        "разобрать строки", "scan",
        [_stamp.условие("разобрана хоть одна строка", True, bool(rows))],
        исход="сработал" if rows else "молчал",
        следствие=f"разобрано строк: {len(rows)}" if rows
        else "ни одной строки — сломан формат таблицы, и вместе с ним слепнет ось статусов"))
    if not rows:
        print("findings_count: ни одной строки не разобрано — замер не состоялся", file=sys.stderr)
        return _итог(ряды, 2, чужое)
    closed = sum(rows.values())
    openi = sorted((f for f, c in rows.items() if not c), key=lambda x: int(x[1:]))
    print(f"всего: {len(rows)} · закрыты: {closed} · открытых: {len(openi)}")
    print("открытые: " + " · ".join(openi))

    if "--bless" in sys.argv:
        FLOOR.write_text(f"{len(rows)}\n", encoding="utf-8")
        print(f"пол поднят до {len(rows)}")
        return _итог(ряды, 0, чужое)
    if "--check" not in sys.argv:
        return _итог(ряды, 0, чужое)
    # Пол, а не потолок: реестр только растёт, поэтому падение числа — это сломанный разбор,
    # а не закрытая находка. Поднимается вместе с новой находкой через `--bless`.
    # Пола нет или он нечитаем — это «улики нет», а не «чисто»: молча выключенный храповик
    # зеленеет на любом числе строк, включая ноль.
    if not FLOOR.exists():
        print(f"findings_count: пола нет — {FLOOR}. Храповик выключен, замер ни с чем не сверен: "
              "заведите пол через --bless", file=sys.stderr)
        ряды.append(_stamp.строка_шага(
            "сверить с полом", "храповик пола",
            [_stamp.условие("пол объявлен и читается числом", True, False)],
            исход="молчал",
            следствие="пола нет — храповик выключен, и любое число строк выглядело бы зелёным"))
        return _итог(ряды, 2, чужое)
    try:
        floor = int(FLOOR.read_text(encoding="utf-8").strip())
    except ValueError:
        print(f"findings_count: пол не читается числом — {FLOOR}", file=sys.stderr)
        ряды.append(_stamp.строка_шага(
            "сверить с полом", "храповик пола",
            [_stamp.условие("пол объявлен и читается числом", True, False)],
            исход="молчал", следствие="пол есть, но не число — сверять не с чем"))
        return _итог(ряды, 2, чужое)
    ряды.append(_stamp.строка_шага(
        "сверить с полом", "храповик пола",
        [_stamp.условие("пол объявлен и читается числом", True, True),
         _stamp.условие("разобранных строк стало МЕНЬШЕ пола", True, len(rows) < floor)],
        исход="сработал" if len(rows) < floor else "молчал",
        следствие=f"реестр ужался: {len(rows)} при поле {floor}" if len(rows) < floor
        else f"разобрано не ниже пола: {len(rows)} при поле {floor}"))
    if len(rows) < floor:
        print(f"findings_count: разобрано {len(rows)} строк при поле {floor} — реестр ужался. "
              "Находки не удаляются, только закрываются: значит сломался разбор таблицы, и вместе "
              "с ним ослеп status_off_registry", file=sys.stderr)
        return _итог(ряды, 1, чужое)
    print(f"реестр читается машиной: {len(rows)} строк при поле {floor}")
    # Чужое дерево судится не нашим полом, и подпись туда была бы вердиктом о чужой мерке.
    if чужое:
        return _итог(ряды, 0, чужое)
    _итог(ряды, 0, чужое)
    return _verdict.close("реестр находок", 0,
                          ".venv/bin/python scripts/guards/findings_count.py --check",
                          улика="есть")


if __name__ == "__main__":
    raise SystemExit(main())
