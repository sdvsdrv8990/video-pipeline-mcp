"""scripts/installer_tui.py — выбор роли машины при установке: что здесь будет стоять.

Первый экран установки спрашивает РОЛЬ машины, а не компоненты, и объявляет выбор: стоит ли здесь
сервер и какой конец туннеля здесь работает. Только stdlib — экран рисуется ДО создания
окружения, ставить в этот момент нечего, и по той же причине объявление пишется строками, а не
библиотекой. Решает пользователь: скрипт ничего не устанавливает и не судит, он записывает выбор.
Нет терминала — работает объявленная переменная окружения, экран не поднимается.
"""

import curses
import locale
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONFIG = ROOT / "config" / "install.yaml"

ЗАГОЛОВОК = "VIDEO PIPELINE MCP — УСТАНОВКА"
ШИРИНА = 62

# Роль машины → что объявляется; выбирается по клиенту: консоли на этой машине туннель не нужен (петля), Claude AI Web
# достаёт сервер только через туннель. Порядок строк здесь И ЕСТЬ порядок пунктов меню.
# `both` пользователю не показывается — он живёт только правым столбцом, как техническое значение.
РОЛИ = (
    ("local", "Local", ("Claude AI Web: MCP-сервер + локальный конец туннеля", "Рабочая машина"),
     (True, "client")),
    ("console", "Console", ("Консоль на этой машине (Claude Code): MCP-сервер без туннеля", "Клиент по петле"),
     (True, "none")),
    ("server", "Server", ("Claude AI Web: MCP-сервер + серверный конец туннеля", "Серверная машина"),
     (True, "server")),
    ("tunnel", "Tunnel", ("Claude AI Web: только туннель, MCP-сервер на другой машине", "Без MCP-сервера"),
     None),  # конец туннеля спрашивает второй экран
)

# Второй экран роли Tunnel: где находится ВТОРОЙ конец.
КОНЦЫ = (
    ("remote", "Удалённый сервер", ("Подключение к туннелю на другой машине",), (False, "client")),
    ("here", "Эта машина", ("Оба конца туннеля работают локально",), (False, "both")),
)

ИМЕНА_КОНЦОВ = {"client": "Tunnel Client", "server": "Tunnel Server",
                "both": "Tunnel Client + Tunnel Server", "none": "без туннеля"}

ВЫБОРЫ = {"local": ("роль", "local"), "console": ("роль", "console"), "server": ("роль", "server"),
          "tunnel-remote": ("конец", "remote"), "tunnel-here": ("конец", "here")}

# Прежний словарь ролей: чтобы старые неинтерактивные прогоны не начали молча ставить другое.
СТАРЫЕ = {"local": (True, "client"), "server": (False, "server"), "both": (True, "both")}


class Отменено(Exception):
    """Пользователь вышел: Esc на первом экране или Ctrl+C."""


def строка_(окно, y: int, x: int, текст: str, атрибут: int = 0) -> None:
    """Печать, не роняющая экран на узком терминале и на последней клетке строки."""
    try:
        окно.addstr(y, x, текст, атрибут)
    except curses.error:
        pass


def рамка(окно, строки: list[tuple[str, int]], подвал: str) -> None:
    # clear, а не erase: следующий экран бывает КОРОЧЕ прежнего, и оптимизация перерисовки
    # оставляла хвост предыдущего внутри рамки — «Tunnelходится второй конец туннеля?».
    окно.clear()
    высота, ширина = окно.getmaxyx()
    # Ширина растёт под содержимое: отчёт приёмки длиннее меню, и фиксированная рамка резала
    # причину отказа на полуслове — ровно ту строку, ради которой отчёт и читают.
    нужно = max([len(т) + 6 for т, _ in строки] + [len(подвал) + 4, len(ЗАГОЛОВОК) + 4, ШИРИНА])
    w = min(нужно, max(20, ширина - 1))
    строка_(окно, 0, 0, "╭" + "─" * (w - 2) + "╮")
    строка_(окно, 1, 0, "│" + ЗАГОЛОВОК.center(w - 2) + "│", curses.A_BOLD)
    строка_(окно, 2, 0, "├" + "─" * (w - 2) + "┤")
    y = 3
    for текст, атрибут in строки:
        if y >= высота - 4:
            break
        строка_(окно, y, 0, "│" + " " * (w - 2) + "│")
        строка_(окно, y, 2, текст[: w - 4], атрибут)
        y += 1
    строка_(окно, y, 0, "├" + "─" * (w - 2) + "┤")
    строка_(окно, y + 1, 0, "│" + подвал.center(w - 2) + "│", curses.A_DIM)
    строка_(окно, y + 2, 0, "╰" + "─" * (w - 2) + "╯")
    окно.refresh()


def меню(окно, вопрос: str, пункты, назад: str, заметка: str = "") -> int | None:
    """Индекс выбранного пункта; None — Esc (назад/выход). Заметка — строка под вопросом."""
    курсор = 0
    while True:
        строки: list[tuple[str, int]] = [(вопрос, curses.A_BOLD), *([(заметка, curses.A_DIM)] if заметка else []), ("", 0)]
        for i, (_, метка, пояснения, _полезное) in enumerate(пункты):
            выбран = i == курсор
            строки.append((("> " if выбран else "  ") + метка,
                           curses.A_REVERSE if выбран else curses.A_BOLD))
            строки += [("      " + п, curses.A_DIM) for п in пояснения]
            строки.append(("", 0))
        рамка(окно, строки, f"↑ ↓ Выбор     Enter Продолжить     Esc {назад}")

        клавиша = окно.getch()
        if клавиша == curses.KEY_UP:
            курсор = (курсор - 1) % len(пункты)
        elif клавиша == curses.KEY_DOWN:
            курсор = (курсор + 1) % len(пункты)
        elif клавиша in (curses.KEY_ENTER, 10, 13):
            return курсор
        elif клавиша == 27:  # Esc
            return None


def _подтверждение(окно, титул: str, ставится: list[str], назначение: str, сейчас: str = "",
                   снимается: tuple[str, ...] = ()) -> bool:
    строки: list[tuple[str, int]] = [(титул, curses.A_BOLD), ("", 0)]
    if сейчас:
        строки += [(сейчас, 0), ("", 0)]
    строки += [("Будет установлено:", 0), ("", 0)]
    строки += [("  ✓ " + что, 0) for что in ставится]
    строки += [("", 0), ("  " + назначение, curses.A_DIM), ("", 0)]
    строки += [("  " + с, curses.A_BOLD) for с in снимается] + ([("", 0)] if снимается else [])
    рамка(окно, строки, "Enter Продолжить     Esc Назад")
    while True:
        клавиша = окно.getch()
        if клавиша in (curses.KEY_ENTER, 10, 13):
            return True
        if клавиша == 27:
            return False


def _экран(окно, было: tuple[bool, str] | None = None) -> tuple[bool, str]:
    curses.curs_set(0)
    окно.keypad(True)
    сейчас = f"Сейчас объявлено: {описание(*было)}" if было else ""
    while True:
        i = меню(окно, "Чем будете подключаться к MCP-серверу?", РОЛИ, "Выход", сейчас)
        if i is None:
            raise Отменено
        _имя, метка, _пояснения, полезное = РОЛИ[i]

        if полезное is None:
            j = меню(окно, "Где находится второй конец туннеля?", КОНЦЫ, "Назад")
            if j is None:
                continue  # Esc второго экрана возвращает к выбору роли, а не выходит из установки
            полезное = КОНЦЫ[j][3]

        mcp, конец = полезное
        назначение = ({"client": "Назначение: рабочая машина",
                       "none": "Назначение: консоль на этой машине — сервер по петле, без туннеля"}.get(
                          конец, "Назначение: серверная машина")) if mcp else "MCP Server не устанавливается."
        if _подтверждение(окно, метка, состав(mcp, конец), назначение, сейчас, снят(было, mcp)):
            return mcp, конец


def записать(mcp: bool, конец: str, path: Path = CONFIG) -> None:
    """Объявление установки. Пишется строками: библиотеки yaml на этом шаге может ещё не быть."""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        "# Объявление установки — пишет установщик, читает core/deploy. Секретов здесь не бывает.\n"
        f"mcp: {'true' if mcp else 'false'}\n"
        f"tunnel: {конец}\n",
        encoding="utf-8")


def объявлено(path: Path = CONFIG) -> tuple[bool, str] | None:
    """Что объявлено сейчас — для «было → станет». Читается строками, как и пишется; нет файла или ключей — None."""
    try:
        строки = path.read_text(encoding="utf-8").splitlines()
    except FileNotFoundError:
        return None
    поля = {к.strip(): з.strip() for к, з in (с.split(":", 1) for с in строки if ":" in с and not с.lstrip().startswith("#"))}
    mcp, конец = поля.get("mcp"), поля.get("tunnel")
    if mcp not in ("true", "false") or конец not in ИМЕНА_КОНЦОВ:
        return None
    return mcp == "true", конец


def состав(mcp: bool, конец: str) -> list[str]:
    """Компоненты машины словами экрана."""
    return (["MCP Server"] if mcp else []) + ([ИМЕНА_КОНЦОВ[конец]] if конец != "none" else [])


def описание(mcp: bool, конец: str) -> str:
    return " + ".join(состав(mcp, конец)) + ("" if mcp else " (без MCP Server)")


def снят(было: tuple[bool, str] | None, mcp: bool) -> tuple[str, ...]:
    """Предупреждение, когда выбор снимает объявленный сервер: повторный запуск ради туннеля не должен убрать его молча."""
    if not (было and было[0] and not mcp):
        return ()
    return ("⚠ MCP Server, объявленный сейчас, снимается:",
            "  ./run.sh не поднимет сервер на этой машине. Сервер и туннель здесь — роль Local.")


def из_среды() -> tuple[bool, str] | None:
    """Неинтерактивный путь для CI и прогонов. Пусто — поднимаем экран."""
    выбор = os.environ.get("VPM_INSTALL_CHOICE", "").strip()
    if выбор:
        if выбор not in ВЫБОРЫ:
            print(f"✗ неизвестный выбор '{выбор}' — допустимо: {', '.join(ВЫБОРЫ)}", file=sys.stderr)
            raise SystemExit(1)
        вид, имя = ВЫБОРЫ[выбор]
        таблица = РОЛИ if вид == "роль" else КОНЦЫ
        return next(строка[3] for строка in таблица if строка[0] == имя)

    старая = os.environ.get("VPM_INSTALL_ROLE", "").strip()
    if старая:
        if старая not in СТАРЫЕ:
            print(f"✗ неизвестная роль '{старая}' — допустимо: {', '.join(СТАРЫЕ)}", file=sys.stderr)
            raise SystemExit(1)
        return СТАРЫЕ[старая]
    return None


def main() -> int:
    locale.setlocale(locale.LC_ALL, "")
    было = объявлено()
    выбор = из_среды()
    if выбор is None:
        if not sys.stdin.isatty():
            print("✗ нет терминала для меню — задай "
                  f"VPM_INSTALL_CHOICE={'|'.join(ВЫБОРЫ)}", file=sys.stderr)
            return 1
        try:
            выбор = curses.wrapper(_экран, было)  # wrapper возвращает терминал в норму и на исключении
        except (Отменено, KeyboardInterrupt):
            print("Установка отменена — ничего не объявлено.")
            return 1
    mcp, конец = выбор
    записать(mcp, конец)
    print(f"Объявлено: MCP {'ставится' if mcp else 'не ставится'}, "
          f"конец туннеля — {конец} → {CONFIG.relative_to(ROOT)}"
          + (f" (было: {описание(*было)})" if было and было != выбор else ""))
    for строка in снят(было, mcp):
        print(строка)
    return 0


if __name__ == "__main__":
    sys.exit(main())
