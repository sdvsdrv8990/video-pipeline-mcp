"""scripts/control_center.py — меню после установки: запустить, настроить, проверить.

Экран, которым заканчивается установка и который открывается потом повторно; установка больше не
уводит человека в настройки сама — они доступны, но обязательным шагом не являются. Ничего не
чинит, зовёт готовое. Диагностика поднимается по требованию, постоянно она выключена. Нет
терминала — печатает отчёт быстрой проверки и выходит, меню не поднимает.
"""

import curses
import locale
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from scripts.installer_tui import меню, рамка  # noqa: E402 — корень в пути ставится строкой выше

# Пункт → (какие проверки каталога гонять, в каком режиме). None вместо набора = режим целиком.
# Отдельные пункты — ВХОДЫ в один механизм, а не его копии: каталог проверок один.
ТУННЕЛЬ = (
    ("состояние", "Состояние", ("Процесс туннеля и его рёбра",), ({"служба"}, "быстрая")),
    ("соединение", "Соединение", ("Доходит ли запрос снаружи до нашего процесса",),
     ({"соединение"}, "быстрая")),
    ("компоненты", "Серверные компоненты", ("Бинари объявленного конца и их версии",),
     ({"компоненты"}, "быстрая")),
    ("быстрая", "Быстрая проверка", ("Всё перечисленное разом, без лишнего трафика",),
     (None, "быстрая")),
    ("полная", "Полная диагностика", ("Плюс тестовый поток, сверка целостности и уборка",),
     (None, "полная")),
    ("логи", "Логи", ("Последние строки журнала сервера",), None),
)

ГЛАВНОЕ = (
    ("запуск", "Запустить", ("Сервер и туннель одной командой",), None),
    ("настройки", "Настройки", ("Модели и провайдеры",), None),
    ("туннель", "Проверить состояние", ("Приёмка туннеля",), None),
    ("выход", "Выйти", (), None),
)


def _установка() -> tuple[bool, str]:
    """Что объявлено на этой машине. Через общую дверь, а не разбором yaml на месте."""
    from core.deploy import install
    return install()


def _отчёт(окно, заголовок: str, строки: list[str]) -> None:
    рамка(окно, [(заголовок, curses.A_BOLD), ("", 0)] + [(с, 0) for с in строки], "Enter — назад")
    while окно.getch() not in (curses.KEY_ENTER, 10, 13, 27):
        pass


def логи(лимит: int = 12) -> list[str]:
    """Хвост свежего журнала. Пусто — это ответ «сервер не запускался», а не поломка."""
    файлы = sorted((ROOT / "logs").glob("*.log"), key=lambda p: p.stat().st_mtime, reverse=True)
    if not файлы:
        return ["журнала ещё нет — сервер не запускался"]
    строки = файлы[0].read_text(encoding="utf-8", errors="replace").splitlines()
    return [f"{файлы[0].name}:", *строки[-лимит:]]


def _проверка(окно, конец: str, только: set[str] | None, режим: str) -> None:
    from core.transport.diagnostics import Диагностика
    отчёт = Диагностика(конец=конец).прогнать(режим, только)
    _отчёт(окно, f"Приёмка туннеля — {режим}", отчёт.строки())


def _туннель(окно, конец: str) -> None:
    while True:
        i = меню(окно, "Туннель", ТУННЕЛЬ, "Назад")
        if i is None:
            return
        имя, _метка, _пояснения, задание = ТУННЕЛЬ[i]
        if задание is None:
            _отчёт(окно, "Логи", логи())
            continue
        только, режим = задание
        _проверка(окно, конец, только, режим)


def _экран(окно) -> str:
    curses.curs_set(0)
    окно.keypad(True)
    _mcp, конец = _установка()
    while True:
        i = меню(окно, "Установка завершена. Что дальше?", ГЛАВНОЕ, "Выход")
        if i is None:
            return "выход"
        имя = ГЛАВНОЕ[i][0]
        if имя == "туннель":
            _туннель(окно, конец)
            continue
        return имя


def main() -> int:
    locale.setlocale(locale.LC_ALL, "")
    _mcp, конец = _установка()
    if not sys.stdin.isatty():
        from core.transport.diagnostics import ОТКАЗ, быстрая
        отчёт = быстрая(конец=конец)
        print("\n".join(отчёт.строки()))
        return 1 if отчёт.вердикт == ОТКАЗ else 0
    try:
        выбор = curses.wrapper(_экран)
    except KeyboardInterrupt:
        return 0
    if выбор == "запуск":
        return subprocess.call([str(ROOT / "run.sh")])
    if выбор == "настройки":
        return subprocess.call([sys.executable, str(ROOT / "scripts" / "configure.py")])
    return 0


if __name__ == "__main__":
    sys.exit(main())
